function bm_write_table(file, B, info, what)
%BM_WRITE_TABLE The _table.md sidecar of a figure drawn from the burst_mode stage: what is drawn, and the per-network numbers.
%
%   bm_write_table(file, B, info, what)
%
% B     bm_load_runs' struct (its index table is read; B.R{1} is the drawn network)
% info  bm_fig8_panels' info, or [] when the figure draws no states
% what  the figure's name, for the heading
%
% See also: fig_burst_mode, fig_supp10_grouped, ied_stim_fig_combined

fid = fopen(file, 'w');
if fid < 0
    error('bm_write_table:Open', 'Cannot write %s.', file);
end
guard = onCleanup(@() fclose(fid));
s = B.settings; T = B.runs; R = B.R{1};
fprintf(fid, '# %s: burst_mode stage\n\n', what);
fprintf(fid, ['Source: `%s`. Network %s under %s (n = %d), a DC step of %g to every neuron at t = %g s ' ...
    '(staircase [0 %g], %g s per level, white-noise probe %g), fs %g Hz, %s. Windows: before %s s, during %s s. ' ...
    'Rates in 1/s: the frozen-gain mode is (lambda_1(M) - 1)/tau_d with tau_d = %g s; the boundary is Re = 0.\n\n'], ...
    B.index_file, s.preset_name, s.condition, R.n, s.dc_level, s.hold_dur, s.dc_level, s.hold_dur, ...
    s.noise_intensity, s.fs, R.ode_solver, mat2str(R.windows.before), mat2str(R.windows.during), R.tau_d);
if ~isempty(info)
    fprintf(fid, 'Drawn network: seed %s. Burst of the zoom: onset %.2f s (window %.2f to %.2f s).\n\n', ...
        mat2str(R.seed), R.bursts.t_on(info.burst), info.zoom);
    fprintf(fid, '| State | Time (s) | Rightmost Re z (1/s) | Bulk radius (1/s) |\n|---|---|---|---|\n');
    for q = 1:numel(info.state_name)
        tt = 'structure'; if q > 1; tt = sprintf('%.2f', info.t_state(q)); end
        fprintf(fid, '| %s | %s | %.2f | %.2f |\n', info.state_name{q}, tt, info.z_right(q), info.rad(q));
    end
    fprintf(fid, '\nComplex plane window: Re %s, Im %s (1/s). Mode axis: %s (1/s).\n\n', ...
        mat2str(info.re_lim, 3), mat2str(info.im_lim, 3), mat2str(info.mode_lim));
end
fprintf(fid, ['## Per network\n\nBursts before / during the step; frozen-gain (FG) and full-Jacobian (FJ) mode: crossings ' ...
    'of the boundary before the step, bursts with a coinciding crossing, median lead of the crossing over the ' ...
    'burst onset (s), share of time beyond the boundary before / during the step, largest Re during the step (1/s); ' ...
    'frozen arm: share beyond during, bursts during, mean E rate during; synchrony rho of the E dendritic potentials ' ...
    'before / during / during with adaptation frozen.\n\n']);
fprintf(fid, ['| Seed | Bursts b/d | FG cross | FG bursts with | FG lead | FJ cross | FJ bursts with | FJ lead | ' ...
    'FG beyond b/d | FJ beyond b/d | FG max d | FJ max d | Frozen beyond d | Frozen bursts d | Frozen rate E d | ' ...
    'Rate E b/d | Gain EE b/d | rho b/d/frozen |\n']);
fprintf(fid, '|%s\n', repmat('---|', 1, 18));
for i = 1:height(T)
    fprintf(fid, ['| %d %d | %d / %d | %d | %d | %.2f | %d | %d | %.2f | %.2f / %.2f | %.2f / %.2f | %+.2f | %+.2f | ' ...
        '%.2f | %d | %.2f | %.3f / %.3f | %.2f / %.2f | %.2f / %.2f / %.2f |\n'], T.seed1(i), T.seed2(i), ...
        T.n_bursts_before(i), T.n_bursts_during(i), T.n_cross_before_frozen_gain(i), ...
        T.n_bursts_with_cross_frozen_gain(i), T.median_lead_frozen_gain(i), T.n_cross_before_full(i), ...
        T.n_bursts_with_cross_full(i), T.median_lead_full(i), T.frac_beyond_before_frozen_gain(i), ...
        T.frac_beyond_during_frozen_gain(i), T.frac_beyond_before_full(i), T.frac_beyond_during_full(i), ...
        T.max_re_during_frozen_gain(i), T.max_re_during_full(i), T.frac_beyond_during_frozen_arm(i), ...
        T.n_bursts_during_frozen_arm(i), T.rate_E_during_frozen_arm(i), T.rate_E_before(i), T.rate_E_during(i), ...
        T.gain_EE_before(i), T.gain_EE_during(i), T.rho_before(i), T.rho_during(i), T.rho_during_frozen_arm(i));
end
fprintf(fid, '\nStage time: %.1f min on %d worker(s); per network %s s.\n', s.minutes, s.n_workers, ...
    strjoin(compose('%.0f', T.seconds'), ', '));
end
