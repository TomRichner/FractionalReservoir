function M = regression_tol_mutations_spread(which_list)
% REGRESSION_TOL_MUTATIONS_SPREAD The deliberate errors in the per-neuron spread that the tolerance tier's spread suite must catch.
%
%   M = regression_tol_mutations_spread()            % the list
%   G = regression_tol_mutations_spread('groups')    % leaf groups for the harness
%   rows = regression_tol_mutate(M, 'reference', 'spread', 'groups', G);
%
% DATA FOR regression_tol_mutate (FD-015). The spread suite of the
% tolerance tier (regression_tol_run, suite 'spread'; reference
% scripts/tests/fixtures/regression_tol_spread.mat) is the gate for later
% work on std_spread and stf_spread. Before it is trusted it has to be
% shown to catch errors in them. Each entry is one minimal one-site edit:
% a file, a text that occurs exactly once in it, and its replacement. THE
% TEXT IS TIED TO THE CODE AS IT STANDS at the commit that added this file.
%
% The rule (route_model, "THE SPREAD"): a neuron's value of a quantity is
% nominal * exp(sigma * z), a ceiling 1 + (G - 1) * exp(sigma * z), with
% sigma the spread of the neuron's cell type and z the quantity's column
% of the neuron's row of std_draws or stf_draws:
%   depression    1 tau_rec_1, 2 tau_rel_1, 3 tau_rec_2, 4 tau_rel_2, 5 n2
%   facilitation  1 tau_dec_1, 2 tau_fac_1, 3 tau_h, 4 G_1 - 1,
%                 5, 6, 7 tau_dec_2, tau_fac_2, G_2 - 1
% and on a chain a neuron whose log(tau_rec2 / tau_rec1) falls below a
% quarter of the nominal log-span has tau_rec2 alone raised to that floor.
%
% THE ERRORS, by where they are:
%   route_pool, compile     every quantity reading another quantity's
%        column (tau_rec1, tau_rel, tau_rec2, n2; tau_dec, tau_fac, tau_h,
%        the ceiling); sigma off by 1e-6, each mechanism; the ceiling
%        jittered as G and not G - 1; the ordering rule omitted, with a
%        floor of half the span, testing the wrong columns, pushing the
%        two refill times apart symmetrically (Plan A 4.3's first rule),
%        lowering tau_rec1 and not raising tau_rec2, and not recording
%        whom it moved; a spread route flagged as not per neuron
%   route_pool, linearize   one entry reading the nominal tau_rel where
%        rhs reads the neuron's own
%   route_product, compile  the same column errors for a product route's
%        components (tau_rec, tau_rel; tau_dec, tau_fac, G; a second
%        component reading the columns after its own); sigma off by 1e-6;
%        the ceiling jittered as G; the zero floor's p_min formed from the
%        nominal values
%   route_product, the zero floor   every neuron given the first neuron's
%        p_min
%   SRNNCellTypePairs       the spread of the wrong presynaptic type, and
%        the wrong type's rows of the draws; the rows of a type reversed;
%        sigma off by 1e-6 at the class; the draw no longer shared by a
%        neuron's routes (each route after the first reads other neurons'
%        rows: a route redrawing its own); two draw columns exchanged;
%        each seed offset set to the other stream's, and to the SFA
%        ladder's; the draw filled row by row (the leading columns then
%        depend on Q); the RNG state not restored after the draws;
%        std_clipped counting a neuron once per route; dynamics_fast,
%        compute_Jacobian_fast and jacobian_times, each alone, computing
%        with the NOMINAL parameters where the others use the drawn ones;
%        route_fields reporting the postsynaptic type's spread, and a
%        spread on a route that has no such mechanism; params.std_spread
%        holding the other mechanism's row
%
% NOT IN THE LIST, each because the tier cannot see it by construction:
%   - the 'twister' pin dropped from rng(seed, 'twister'): the client's
%     generator is the Mersenne twister already, so nothing changes here.
%     It matters on a parallel worker, which no tolerance suite runs on.
%   - the row check of std_route_factor / stf_route_factor
%     (RouteFactorRows): the suite hands them whole routes, as all code
%     does today. test_std_spread asserts it.
%   - steady_state with per-neuron parameters: no network code calls it.
%     test_route_models (2g) asserts it.
%
% See also: regression_tol_mutate, regression_tol_mutations_chain,
%           regression_tol_mutations_stf_chain, regression_tol_check,
%           route_model, test_std_spread
arguments
    which_list (1,:) char {mustBeMember(which_list, {'list', 'groups'})} = 'list'
end
if strcmp(which_list, 'groups')
    % What kind of leaf saw the error (first match wins; the overridden
    % groups of regression_tol_settings first), for the suite's keys.
    M = { ...
        'ov_orth_defect',   '(^|\.)orth_defect_max$'; ...
        'ov_fd_jacobian',   '(^|\.)finite_difference_J$'; ...
        'ov_qr',            '^stable\.estimators\.\w+\.qr\.'; ...
        'ov_mc',            '^stable\.mc\.\w+\.(MC|R2)$'; ...
        'pw_draws',         '^pointwise\..*\.view\.(std_draws|stf_draws)$'; ...
        'pw_clipped',       '^pointwise\..*\.view\.(std_clipped|realised\.\w+\.clipped)$'; ...
        'pw_realised',      '^pointwise\..*\.view\.realised\.'; ...
        'pw_route_fields',  '^pointwise\..*\.view\.route\.'; ...
        'pw_view',          '^pointwise\..*\.view\.'; ...
        'pw_dS',            '^pointwise\..*\.dS$'; ...
        'pw_J',             '^pointwise\..*\.J(\{\d+\}|#size)$'; ...
        'pw_JY',            '^pointwise\..*\.JY$'; ...
        'pw_rate_theta',    '^pointwise\..*\.(rate|synaptic_output)\.'; ...
        'pw_std_factor',    '^pointwise\..*\.std_factor\.'; ...
        'pw_stf_factor',    '^pointwise\..*\.stf_factor\.'; ...
        'pw_other',         '^pointwise\.'; ...
        'st_clipped',       '^stable\.model\..*\.std_clipped$'; ...
        'st_trajectory',    '^stable\.model\.[\w.]+\.(S0|S_kept|t_kept|W|plot_data\.|tau_a_clipped)'; ...
        'st_std_factor',    '^stable\.model\.[\w.]+\.std_factor\.'; ...
        'st_stf_factor',    '^stable\.model\.[\w.]+\.stf_factor\.'; ...
        'st_topk',          '^stable\.model\.[\w.]+\.(lya_results|lya_summary)\.'; ...
        'st_gain',          '^stable\.extra\.\w+\.transient_gain\.'; ...
        'st_benettin',      '^stable\.estimators\.\w+\.benettin\.'; ...
        'st_sweep',         '^stable\.sweep\.'; ...
        'st_other',         '^stable\.'};
    return;
end
pairs = 'src/model/SRNNCellTypePairs.m';
pool = 'src/model/routes/route_pool.m';
product = 'src/model/routes/route_product.m';
M = struct('name', {}, 'file', {}, 'find', {}, 'replace', {}, 'what', {});

%% route_pool, compile: each quantity's column
% {name, the line, the column it reads, a wrong column, what}
lines = { ...
    'tau_rec1', 'P.tau_rec1 = P.tau_rec1 .* e(:, 1);', '1', '2', 'tau_rec1 reads column 2, tau_rel''s'; ...
    'tau_rel',  'P.tau_rel  = P.tau_rel .* e(:, 2);', '2', '1', 'tau_rel reads column 1, tau_rec1''s'; ...
    'tau_rec2', 'P.tau_rec2 = P.tau_rec2 .* e(:, 3);', '3', '4', ...
        'tau_rec2 reads column 4, a product route''s tau_rel_2 (the chain and the product then differ in tau_rec_2)'; ...
    'n2',       'P.n2       = P.n2 .* e(:, 5);', '5', '3', 'n2 reads column 3, tau_rec2''s'; ...
    'tau_dec',  'P.tau_dec = P.tau_dec .* e(:, 1);', '1', '2', 'tau_dec reads column 2, tau_fac''s'; ...
    'tau_fac',  'P.tau_fac = P.tau_fac .* e(:, 2);', '2', '1', 'tau_fac reads column 1, tau_dec''s'; ...
    'G',        'P.G       = 1 + (P.G - 1) .* e(:, 4);', '4', '3', 'the ceiling reads column 3, tau_h''s'; ...
    'tau_h',    'P.tau_h = P.tau_h .* e(:, 3);', '3', '4', 'tau_h reads column 4, the ceiling''s'};
for k = 1:size(lines, 1)
    M = add(M, ['pool_col_' lines{k, 1}], pool, lines{k, 2}, ...
        strrep(lines{k, 2}, ['e(:, ' lines{k, 3} ')'], ['e(:, ' lines{k, 4} ')']), ...
        ['route_pool, compile: ' lines{k, 5}]);
end

%% route_pool, compile: sigma, the ceiling, the ordering rule
M = add(M, 'pool_std_sigma_1e-6', pool, 'e = exp(opts.std_sigma .* z_std);', ...
    'e = exp((1 + 1e-6) .* opts.std_sigma .* z_std);', ...
    'route_pool, compile: the depression spread off by 1e-6 relative');
M = add(M, 'pool_stf_sigma_1e-6', pool, 'e = exp(opts.stf_sigma .* z_stf);', ...
    'e = exp((1 + 1e-6) .* opts.stf_sigma .* z_stf);', ...
    'route_pool, compile: the facilitation spread off by 1e-6 relative');
M = add(M, 'pool_G_not_excess', pool, 'P.G       = 1 + (P.G - 1) .* e(:, 4);', ...
    'P.G       = P.G .* e(:, 4);', ...
    'route_pool, compile: the ceiling jittered as G, not as G - 1 (it can then fall below 1)');
M = add(M, 'pool_floor_omitted', pool, 'if span > 0', 'if false', ...
    'route_pool, compile: the ordering rule omitted');
M = add(M, 'pool_floor_half_span', pool, 'floor_gap = span / 4;', 'floor_gap = span / 2;', ...
    'route_pool, compile: the floor at half the nominal log-span, not a quarter');
M = add(M, 'pool_floor_wrong_columns', pool, ...
    'gap = span + opts.std_sigma .* (z_std(:, 3) - z_std(:, 1));', ...
    'gap = span + opts.std_sigma .* (z_std(:, 3) - z_std(:, 2));', ...
    'route_pool, compile: the ordering rule tests tau_rec2 against column 2 (tau_rel''s draw), so it moves other neurons');
M = add(M, 'pool_floor_symmetric', pool, ...
    'P.tau_rec2(short) = P.tau_rec1(short) .* exp(floor_gap);', ...
    ['mid = sqrt(P.tau_rec1(short) .* P.tau_rec2(short)); P.tau_rec1(short) = mid .* exp(-floor_gap / 2); ' ...
     'P.tau_rec2(short) = mid .* exp(floor_gap / 2);'], ...
    ['route_pool, compile: the two refill times pushed apart symmetrically about their log-midpoint ' ...
     '(Plan A 4.3''s first rule): tau_rec1 moves']);
M = add(M, 'pool_floor_moves_tau_rec1', pool, ...
    'P.tau_rec2(short) = P.tau_rec1(short) .* exp(floor_gap);', ...
    'P.tau_rec1(short) = P.tau_rec2(short) .* exp(-floor_gap);', ...
    'route_pool, compile: the floor is met by lowering tau_rec1 and not by raising tau_rec2');
M = add(M, 'pool_clipped_not_recorded', pool, 'P.clipped = short;', 'P.clipped = false(npre, 1);', ...
    'route_pool, compile: the neurons the ordering rule moved are not recorded (the values are right, std_clipped is zero)');

M = add(M, 'pool_jittered_false', pool, 'P.jittered = ~isempty(z_std) || ~isempty(z_stf);', ...
    'P.jittered = false;', ...
    ['route_pool, compile: a spread route says its parameters are not per neuron (std_route_factor would then ' ...
     'serve an array with fewer rows than neurons)']);

%% route_pool, linearize: the nominal where rhs reads the drawn value
M = add(M, 'pool_linearize_nominal_tau_rel', pool, 'use = g .* r ./ P.tau_rel;', ...
    'use = g .* r ./ P.nominal.tau_rel;', ...
    'route_pool, linearize: (b1, b1) on a facilitated route formed with the nominal tau_rel, where rhs uses each neuron''s own');
M = add(M, 'pool_linearize_nominal_tau_rec2', pool, 'A(:, ns + 2) = -1 ./ P.tau_rec2 - q .* empty_u;', ...
    'A(:, ns + 2) = -1 ./ P.nominal.tau_rec(2) - q .* empty_u;', ...
    'route_pool, linearize: (b2, b2) formed with the nominal tau_rec2');

%% route_product, compile
M = add(M, 'product_col_tau_rec', product, 'P.tau_rest(:, m)  = P.tau_rest(:, m) .* e(:, rec_col);', ...
    'P.tau_rest(:, m)  = P.tau_rest(:, m) .* e(:, rec_col + 1);', ...
    'route_product, compile: each tau_rec reads the next column, its component''s tau_rel');
M = add(M, 'product_col_tau_rel', product, 'P.tau_drive(:, m) = P.tau_drive(:, m) .* e(:, rec_col + 1);', ...
    'P.tau_drive(:, m) = P.tau_drive(:, m) .* e(:, rec_col);', ...
    'route_product, compile: each tau_rel reads its component''s tau_rec column');
M = add(M, 'product_col_second_component', product, 'rec_col = 2 * m - 1 + (m >= 3);', ...
    'rec_col = 2 * m - 1 + (m >= 2);', ...
    ['route_product, compile: the second component reads columns 4 and 5 (tau_rel_2''s and the chain''s n2), ' ...
     'so product MTS and chained MTS no longer share the draw behind tau_rec_2']);
M = add(M, 'product_col_tau_dec', product, 'P.tau_rest(:, g)  = P.tau_rest(:, g) .* e(:, dec_col);', ...
    'P.tau_rest(:, g)  = P.tau_rest(:, g) .* e(:, dec_col + 1);', ...
    'route_product, compile: each tau_dec reads its component''s tau_fac column');
M = add(M, 'product_col_tau_fac', product, 'P.tau_drive(:, g) = P.tau_drive(:, g) .* e(:, dec_col + 1);', ...
    'P.tau_drive(:, g) = P.tau_drive(:, g) .* e(:, dec_col);', ...
    'route_product, compile: each tau_fac reads its component''s tau_dec column');
M = add(M, 'product_col_G', product, 'G_col = dec_col + 2 + (l == 1);', 'G_col = dec_col + 2;', ...
    'route_product, compile: the first ceiling reads column 3, the pool model''s tau_h');
M = add(M, 'product_std_sigma_1e-6', product, 'e = exp(opts.std_sigma .* z_std);', ...
    'e = exp((1 + 1e-6) .* opts.std_sigma .* z_std);', ...
    'route_product, compile: the depression spread off by 1e-6 relative');
M = add(M, 'product_stf_sigma_1e-6', product, 'e = exp(opts.stf_sigma .* z_stf);', ...
    'e = exp((1 + 1e-6) .* opts.stf_sigma .* z_stf);', ...
    'route_product, compile: the facilitation spread off by 1e-6 relative');
M = add(M, 'product_G_not_excess', product, 'P.target(:, g)    = 1 + (P.target(:, g) - 1) .* e(:, G_col);', ...
    'P.target(:, g)    = P.target(:, g) .* e(:, G_col);', ...
    'route_product, compile: the ceilings jittered as G, not as G - 1');
M = add(M, 'product_jittered_std_only', product, 'P.jittered = ~isempty(z_std) || ~isempty(z_stf);', ...
    'P.jittered = ~isempty(z_std);', ...
    'route_product, compile: a route whose facilitation alone is spread says its parameters are not per neuron');
M = add(M, 'product_p_min_nominal', product, 'at_ceiling = steady_state(1, P);', ...
    ['Pn = P; Pn.tau_rest = per_neuron([nominal.tau_rec, nominal.tau_dec], opts.npre); ' ...
     'Pn.tau_drive = per_neuron([nominal.tau_rel, nominal.tau_fac], opts.npre); at_ceiling = steady_state(1, Pn);'], ...
    'route_product, compile: the zero floor''s p_min formed from the nominal values, not each neuron''s own');
M = add(M, 'product_p_min_first_neuron', product, 'D = (D - P.p_min) ./ (1 - P.p_min);', ...
    'D = (D - P.p_min(1)) ./ (1 - P.p_min(1));', ...
    'route_product, the zero floor: every neuron mapped with the first neuron''s p_min');

%% SRNNCellTypePairs: which spread and which rows a route is handed
M = add(M, 'class_std_sigma_wrong_type', pairs, 'spread.std_sigma = obj.std_spread(pre);', ...
    'spread.std_sigma = obj.std_spread(C + 1 - pre);', ...
    'compile_synapse_config: a route is handed the depression spread of another presynaptic type');
M = add(M, 'class_stf_sigma_wrong_type', pairs, 'spread.stf_sigma = obj.stf_spread(pre);', ...
    'spread.stf_sigma = obj.stf_spread(C + 1 - pre);', ...
    'compile_synapse_config: a route is handed the facilitation spread of another presynaptic type');
M = add(M, 'class_std_rows_wrong_type', pairs, 'spread.std_z = obj.std_draws(type_rows{pre}, :);', ...
    'spread.std_z = obj.std_draws(type_rows{C + 1 - pre}, :);', ...
    ['compile_synapse_config: a route is handed the draws of another type''s neurons (the uniform network has ' ...
     'two types of equal size, so nothing throws there; the four-type network''s cases throw)']);
M = add(M, 'class_std_rows_reversed', pairs, 'spread.std_z = obj.std_draws(type_rows{pre}, :);', ...
    'spread.std_z = obj.std_draws(flip(type_rows{pre}), :);', ...
    'compile_synapse_config: the depression draws of a type handed over in reverse neuron order');
M = add(M, 'class_stf_rows_reversed', pairs, 'spread.stf_z = obj.stf_draws(type_rows{pre}, :);', ...
    'spread.stf_z = obj.stf_draws(flip(type_rows{pre}), :);', ...
    'compile_synapse_config: the facilitation draws of a type handed over in reverse neuron order');
M = add(M, 'class_std_sigma_1e-6', pairs, 'spread.std_sigma = obj.std_spread(pre);', ...
    'spread.std_sigma = (1 + 1e-6) * obj.std_spread(pre);', ...
    'compile_synapse_config: the depression spread off by 1e-6 relative (the property and route_fields right)');
M = add(M, 'class_stf_sigma_1e-6', pairs, 'spread.stf_sigma = obj.stf_spread(pre);', ...
    'spread.stf_sigma = (1 + 1e-6) * obj.stf_spread(pre);', ...
    'compile_synapse_config: the facilitation spread off by 1e-6 relative');
M = add(M, 'class_std_route_redraws', pairs, '''std_sigma'', spread.std_sigma, ''std_z'', spread.std_z, ...', ...
    '''std_sigma'', spread.std_sigma, ''std_z'', circshift(spread.std_z, post - 1, 1), ...', ...
    ['compile_synapse_config: the draw is no longer shared by a neuron''s routes: every route after the first ' ...
     'reads other neurons'' rows (a route with draws of its own)']);
M = add(M, 'class_stf_route_redraws', pairs, '''stf_sigma'', spread.stf_sigma, ''stf_z'', spread.stf_z));', ...
    '''stf_sigma'', spread.stf_sigma, ''stf_z'', circshift(spread.stf_z, post - 1, 1)));', ...
    'compile_synapse_config: the facilitation draw is no longer shared by a neuron''s routes');
M = add(M, 'class_std_columns_1_2_exchanged', pairs, 'spread.std_z = obj.std_draws(type_rows{pre}, :);', ...
    'spread.std_z = obj.std_draws(type_rows{pre}, [2 1 3:end]);', ...
    'compile_synapse_config: columns 1 and 2 of the depression draws exchanged for every model');
M = add(M, 'class_stf_columns_3_4_exchanged', pairs, 'spread.stf_z = obj.stf_draws(type_rows{pre}, :);', ...
    'spread.stf_z = obj.stf_draws(type_rows{pre}, [1 2 4 3 5:end]);', ...
    'compile_synapse_config: columns 3 and 4 of the facilitation draws exchanged (tau_h and the ceiling)');

%% SRNNCellTypePairs: the draws
M = add(M, 'class_std_seed_is_stf', pairs, 'seed_std = obj.rng_seeds(1) + 32452843;', ...
    'seed_std = obj.rng_seeds(1) + 49979687;', ...
    'build_synapse_spread: the depression stream''s seed offset equal to the facilitation stream''s');
M = add(M, 'class_stf_seed_is_std', pairs, 'seed_stf = obj.rng_seeds(1) + 49979687;', ...
    'seed_stf = obj.rng_seeds(1) + 32452843;', ...
    'build_synapse_spread: the facilitation stream''s seed offset equal to the depression stream''s');
M = add(M, 'class_std_seed_is_tau_a', pairs, 'seed_std = obj.rng_seeds(1) + 32452843;', ...
    'seed_std = obj.rng_seeds(1) + 15485863;', ...
    'build_synapse_spread: the depression stream''s seed offset equal to the SFA ladder''s');
M = add(M, 'class_std_draw_row_major', pairs, 'obj.std_draws = randn(obj.n, Q);', ...
    'obj.std_draws = randn(Q, obj.n)'';', ...
    'build_synapse_spread: the depression draws filled row by row (a neuron''s leading columns then depend on Q)');
M = add(M, 'class_stf_draw_row_major', pairs, 'obj.stf_draws = randn(obj.n, Q);', ...
    'obj.stf_draws = randn(Q, obj.n)'';', ...
    'build_synapse_spread: the facilitation draws filled row by row');
M = add(M, 'class_rng_not_restored', pairs, ...
    ['                obj.stf_draws = randn(obj.n, Q);' newline '            end' newline '            rng(stream_state);'], ...
    ['                obj.stf_draws = randn(obj.n, Q);' newline '            end'], ...
    'build_synapse_spread: the global RNG state is not restored after the draws (x0 is drawn from what they leave behind)');
M = add(M, 'class_clipped_counts_routes', pairs, 'moved = moved | P.clipped;', 'moved = [moved; P.clipped];', ...
    'build_synapse_spread: std_clipped counts a moved neuron once per chain route');

%% SRNNCellTypePairs: one routine alone computing with the nominal parameters
nominal_P = ['subsref(SRNNCellTypePairs.compile_route(R.cfg, setfield(setfield(R.opts, ''std_sigma'', 0), ' ...
    '''stf_sigma'', 0)), substruct(''.'', ''P''))'];
M = add(M, 'class_dynamics_nominal', pairs, ...
    '[ds, F] = model.rhs(reshape(S(R.idx), npre, P.ns), pre_rate, P);', ...
    ['[ds, F] = model.rhs(reshape(S(R.idx), npre, P.ns), pre_rate, ' nominal_P ');'], ...
    'dynamics_fast computes with the nominal parameters; both Jacobians and the unpacking use each neuron''s own');
M = add(M, 'class_jacobian_nominal', pairs, ...
    '[A, B, F, Fs] = model.linearize(reshape(S(row_s), npre, ns), pre_rate, P);', ...
    ['[A, B, F, Fs] = model.linearize(reshape(S(row_s), npre, ns), pre_rate, ' nominal_P ');'], ...
    'compute_Jacobian_fast computes with the nominal parameters; dynamics_fast and jacobian_times use each neuron''s own');
M = add(M, 'class_jacobian_times_nominal', pairs, ...
    '[A, B, F, Fs] = model.linearize(reshape(S(R.idx), npre, ns), pre_rate, P);', ...
    ['[A, B, F, Fs] = model.linearize(reshape(S(R.idx), npre, ns), pre_rate, ' nominal_P ');'], ...
    'jacobian_times computes with the nominal parameters; dynamics_fast and compute_Jacobian_fast use each neuron''s own');
M = add(M, 'class_unpack_nominal', pairs, 'reshape(R.model.output(s, P), npre, nt) .* rate(pre_idx, :);', ...
    ['reshape(R.model.output(s, ' nominal_P '), npre, nt) .* rate(pre_idx, :);'], ...
    ['unpack_and_compute_states forms the synaptic output with the nominal parameters (it differs only where ' ...
     'the output factor reads one: the zero floor''s p_min)']);

%% SRNNCellTypePairs: what a route's comparable data and params say
M = add(M, 'class_route_fields_post_spread', pairs, 'sig.std_spread = params.std_spread(pre);', ...
    'sig.std_spread = params.std_spread(post);', ...
    'route_fields reports the depression spread of the route''s POSTsynaptic type');
M = add(M, 'class_route_fields_stf_everywhere', pairs, ...
    'if sig.n_g > 0 && isfield(params, ''stf_spread'') && ~isempty(params.stf_spread)', ...
    'if isfield(params, ''stf_spread'') && ~isempty(params.stf_spread)', ...
    'route_fields reports a facilitation spread on routes that have no facilitation');
M = add(M, 'class_params_std_spread_is_stf', pairs, 'params.std_spread = obj.std_spread;', ...
    'params.std_spread = obj.stf_spread;', ...
    'get_params: params.std_spread holds the facilitation spreads (the routes are compiled right)');
