function M = regression_tol_mutations_chain(which_list)
% REGRESSION_TOL_MUTATIONS_CHAIN The deliberate errors in chained depression that the tolerance tier's chain suite must catch.
%
%   M = regression_tol_mutations_chain()            % the list
%   G = regression_tol_mutations_chain('groups')    % leaf groups for the harness
%   rows = regression_tol_mutate(M, 'reference', 'chain', 'groups', G);
%
% DATA FOR regression_tol_mutate (Plan A, section 7.3, step 5). The chain
% suite of the tolerance tier (regression_tol_run, suite 'chain';
% reference scripts/tests/fixtures/regression_tol_chain.mat) is the gate
% for work on route_pool, chained facilitation first. Before it is trusted
% it has to be shown to catch errors in the chain. Each entry is one
% minimal one-site edit: a file, a text that occurs exactly once in it,
% and its replacement. THE TEXT IS TIED TO THE CODE AS IT STANDS at the
% commit that added this file; when route_pool is extended the harness
% refuses an entry whose text is gone and the list is written again.
%
% THE ERRORS, by where they are:
%   route_pool, linearize   each of the four entries of the 2 x 2 A
%        dropped, with its sign flipped, and scaled by 1 + 1e-9; B dropped,
%        sign, 1e-9, and written in the reserve's row; F (as b2, and
%        1e-9); Fs (in the reserve's column, 1e-9, and as if F were b1 b2)
%   route_pool, rhs         each of the four terms of (C1) and (C2)
%        dropped and scaled by 1 + 1e-6; the factor returned as b1 b2
%   route_pool, compile     tau_rec1, tau_rec2, tau_rel, n2 off by 1e-6 in
%        the per-neuron values the arithmetic reads (the nominal rows, and
%        so the parameter view, right); n2 off in the nominal row; one
%        neuron's n2; the coupling understated
%   route_pool, initial, output, depression
%   route_model             the registry handing a chain route the product
%        model (it then runs as a two-component product, silently)
%   SRNNCellTypePairs       the 2 x 2 transposed in the assembled Jacobian;
%        the full-A branch of jacobian_times transposed, scaled, and
%        scaled in its last variable; A_is_diagonal forced; a chain
%        route's b1 and b2 rows exchanged; the b columns reversed in the
%        unpacking; params.std_n2
% The class-level errors that are not specific to a chain (a dropped
% block, a term of jacobian_times, the SFA ladder, the activation) are in
% regression_tol_mutations_post_refactor and are run against the anchor.
%
% NAMING. A<m><k> is entry (m, k) of A = d(ds_m)/d(s_k), with 1 the
% releasable pool and 2 the reserve.
%
% See also: regression_tol_mutate, regression_tol_mutations_post_refactor,
%           regression_tol_check, route_pool
arguments
    which_list (1,:) char {mustBeMember(which_list, {'list', 'groups'})} = 'list'
end
if strcmp(which_list, 'groups')
    % What kind of leaf saw the error (first match wins; the overridden
    % groups of regression_tol_settings first), for the chain suite's keys.
    M = { ...
        'ov_orth_defect',   '(^|\.)orth_defect_max$'; ...
        'ov_fd_jacobian',   '(^|\.)finite_difference_J$'; ...
        'ov_qr',            '^stable\.estimators\.\w+\.qr\.'; ...
        'ov_mc',            '^stable\.mc\.\w+\.(MC|R2)$'; ...
        'pw_view',          '^pointwise\..*\.view\.'; ...
        'pw_dS',            '^pointwise\..*\.dS$'; ...
        'pw_J',             '^pointwise\..*\.J(\{\d+\}|#size)$'; ...
        'pw_JY',            '^pointwise\..*\.JY$'; ...
        'pw_rate_theta',    '^pointwise\..*\.(rate|synaptic_output)\.'; ...
        'pw_std_factor',    '^pointwise\..*\.std_factor\.'; ...
        'pw_other',         '^pointwise\.'; ...
        'st_trajectory',    '^stable\.model\.\w+\.\w+\.(S0|S_kept|t_kept|W|plot_data\.|tau_a_clipped)'; ...
        'st_std_factor',    '^stable\.model\.\w+\.\w+\.std_factor\.'; ...
        'st_topk',          '^stable\.model\.\w+\.\w+\.(lya_results|lya_summary)\.'; ...
        'st_gain',          '^stable\.extra\.\w+\.transient_gain\.'; ...
        'st_benettin',      '^stable\.estimators\.\w+\.benettin\.'; ...
        'st_sweep',         '^stable\.sweep\.'; ...
        'st_other',         '^stable\.'};
    return;
end
pairs = 'src/model/SRNNCellTypePairs.m';
pool = 'src/model/routes/route_pool.m';
registry = 'src/model/routes/route_model.m';
M = struct('name', {}, 'file', {}, 'find', {}, 'replace', {}, 'what', {});

%% route_pool, linearize: the four entries of A
% The line as it stands; the entries are (1,1), (2,1), (1,2), (2,2).
A_line = 'A = reshape([-full_u - r ./ P.tau_rel, q .* full_u, empty_u, -1 ./ P.tau_rec2 - q .* empty_u], ...';
entry = {'-full_u - r ./ P.tau_rel', 'q .* full_u', 'empty_u', '-1 ./ P.tau_rec2 - q .* empty_u'};
label = {'A11', 'A21', 'A12', 'A22'};
meaning = {'d(db1)/db1 = -b2/tau_rec1 - r/tau_rel', 'd(db2)/db1 = b2/(n2 tau_rec1)', ...
    'd(db1)/db2 = (1 - b1)/tau_rec1', 'd(db2)/db2 = -1/tau_rec2 - (1 - b1)/(n2 tau_rec1)'};
kinds = {'dropped', '0 .* (%s)', 'dropped'; ...
         'sign',    '-(%s)',     'with its sign flipped'; ...
         '1e-9',    '(1 + 1e-9) .* (%s)', 'scaled by 1 + 1e-9'};
for e = 1:4
    for k = 1:size(kinds, 1)
        parts = entry;
        parts{e} = sprintf(kinds{k, 2}, entry{e});
        patched = sprintf('A = reshape([%s, %s, %s, %s], ...', parts{:});
        M = add(M, sprintf('chain_%s_%s', label{e}, kinds{k, 1}), pool, A_line, patched, ...
            sprintf('linearize: %s, %s %s', label{e}, meaning{e}, kinds{k, 3}));
    end
end

%% route_pool, linearize: B, F, Fs
B_line = 'B = [-b1 ./ P.tau_rel, zeros(npre, 1)];';
M = add(M, 'chain_B_dropped', pool, B_line, 'B = [0 .* b1 ./ P.tau_rel, zeros(npre, 1)];', ...
    'linearize: B = d(db1)/dr dropped (the (s, x) and (s, a) blocks of both Jacobian routines)');
M = add(M, 'chain_B_sign', pool, B_line, 'B = [b1 ./ P.tau_rel, zeros(npre, 1)];', ...
    'linearize: B with its sign flipped');
M = add(M, 'chain_B_1e-9', pool, B_line, 'B = [-(1 + 1e-9) .* b1 ./ P.tau_rel, zeros(npre, 1)];', ...
    'linearize: B scaled by 1 + 1e-9');
M = add(M, 'chain_B_on_reserve', pool, B_line, 'B = [zeros(npre, 1), -b1 ./ P.tau_rel];', ...
    'linearize: B written in the reserve''s row (as if the rate released from the reserve)');
Fs_line = 'Fs = [ones(npre, 1), zeros(npre, 1)];';
M = add(M, 'chain_lin_F_b2', pool, Fs_line, [Fs_line ' F = b2;'], ...
    'linearize: the output factor returned as the reserve b2');
M = add(M, 'chain_lin_F_1e-9', pool, Fs_line, [Fs_line ' F = F .* (1 + 1e-9);'], ...
    'linearize: the output factor scaled by 1 + 1e-9 (the recurrent (x, x) and (x, a) blocks)');
M = add(M, 'chain_Fs_on_reserve', pool, Fs_line, 'Fs = [zeros(npre, 1), ones(npre, 1)];', ...
    'linearize: dF/ds in the reserve''s column (the (x, s) block reads b2 where it is b1)');
M = add(M, 'chain_Fs_1e-9', pool, Fs_line, 'Fs = [(1 + 1e-9) .* ones(npre, 1), zeros(npre, 1)];', ...
    'linearize: dF/db1 scaled by 1 + 1e-9');
M = add(M, 'chain_Fs_as_product', pool, Fs_line, 'Fs = [b2, b1];', ...
    'linearize: dF/ds as if the factor were b1 b2, the product''s');

%% route_pool, rhs: the terms of (C1) and (C2)
ds_line = 'ds = [refill - b1 .* r ./ P.tau_rel, (1 - b2) ./ P.tau_rec2 - refill ./ P.n2];';
term = {'refill', 'b1 .* r ./ P.tau_rel', '(1 - b2) ./ P.tau_rec2', 'refill ./ P.n2'};
term_name = {'C1_refill', 'C1_release', 'C2_recovery', 'C2_loss'};
term_what = {'(C1): the refill of the releasable pool from the reserve, b2 (1 - b1)/tau_rec1', ...
    '(C1): the release b1 r/tau_rel', '(C2): the reserve''s own recovery (1 - b2)/tau_rec2', ...
    '(C2): the reserve''s loss to the releasable pool, (1/n2) b2 (1 - b1)/tau_rec1'};
for e = 1:4
    for k = 1:2
        parts = term;
        if k == 1
            parts{e} = ['0 .* ' term{e}];
            tag = 'dropped'; how = 'dropped';
        else
            parts{e} = ['(1 + 1e-6) .* ' term{e}];
            tag = '1e-6'; how = 'scaled by 1 + 1e-6';
        end
        patched = sprintf('ds = [%s - %s, %s - %s];', parts{:});
        M = add(M, sprintf('chain_%s_%s', term_name{e}, tag), pool, ds_line, patched, ...
            sprintf('rhs, %s, %s', term_what{e}, how));
    end
end
M = add(M, 'chain_rhs_F_b1b2', pool, [ds_line newline 'F = b1;'], [ds_line newline 'F = b1 .* b2;'], ...
    'rhs: the output factor returned as b1 b2 (the right-hand side alone; the linearisation keeps b1)');

%% route_pool, compile: the parameters the arithmetic reads, the coupling
M = add(M, 'chain_P_tau_rec1_1e-6', pool, ...
    'P.tau_rec1 = repmat(nominal.tau_rec(1), opts.npre, 1);', ...
    'P.tau_rec1 = repmat(nominal.tau_rec(1), opts.npre, 1) .* (1 + 1e-6);', ...
    'the per-neuron tau_rec1 off by 1e-6 with the nominal row right, so the parameter view cannot see it');
M = add(M, 'chain_P_tau_rec2_1e-6', pool, ...
    'P.tau_rec2 = repmat(nominal.tau_rec(2), opts.npre, 1);', ...
    'P.tau_rec2 = repmat(nominal.tau_rec(2), opts.npre, 1) .* (1 + 1e-6);', ...
    'the per-neuron tau_rec2 (the reserve''s refill) off by 1e-6, nominal right');
M = add(M, 'chain_P_tau_rel_1e-6', pool, ...
    'P.tau_rel  = repmat(nominal.tau_rel, opts.npre, 1);', ...
    'P.tau_rel  = repmat(nominal.tau_rel, opts.npre, 1) .* (1 + 1e-6);', ...
    'the per-neuron tau_rel off by 1e-6, nominal right');
M = add(M, 'chain_P_n2_1e-6', pool, ...
    'P.n2       = repmat(nominal.n2, opts.npre, 1);', ...
    'P.n2       = repmat(nominal.n2, opts.npre, 1) .* (1 + 1e-6);', ...
    'the per-neuron n2 off by 1e-6, nominal right');
M = add(M, 'chain_P_one_neuron_n2_1e-6', pool, ...
    'P.n2       = repmat(nominal.n2, opts.npre, 1);', ...
    'P.n2       = repmat(nominal.n2, opts.npre, 1); P.n2(1) = P.n2(1) .* (1 + 1e-6);', ...
    'ONE neuron''s n2 off by 1e-6 (the first neuron of every presynaptic type with a chain route)');
M = add(M, 'chain_nominal_n2_1e-6', pool, ...
    '''n2'', double(n2), ''std_model'', ''chain'');', ...
    '''n2'', double(n2) .* (1 + 1e-6), ''std_model'', ''chain'');', ...
    'n2 off by 1e-6 in the nominal row (and so in the per-neuron values, the signature and params.std_n2)');
M = add(M, 'chain_params_std_n2_1e-6', pairs, ...
    'pair.std_n2(pre, post) = nominal.n2;', ...
    'pair.std_n2(pre, post) = nominal.n2 .* (1 + 1e-6);', ...
    'params.std_n2, the copy display code reads, off by 1e-6 (no arithmetic reads it)');
M = add(M, 'chain_coupling_understated', pool, ...
    'P.coupling = true(2);', ...
    'P.coupling = logical(eye(2));', ...
    ['compile: the coupling stated diagonal. jacobian_times trusts it and applies only the diagonal of A; ' ...
     'the assembled Jacobian takes all of A']);
M = add(M, 'chain_A_is_diagonal_forced', pairs, ...
    '''A_is_diagonal'', isdiag(P.coupling));', ...
    '''A_is_diagonal'', true);', ...
    'compile_route: every route marked diagonal whatever its model states (the same error on the class''s side)');

%% route_pool: initial, output, depression
M = add(M, 'chain_init_b1_1e-6', pool, 's0 = [1 1];', 's0 = [1 - 1e-6, 1];', ...
    'initial: the releasable pool starting at 1 - 1e-6');
M = add(M, 'chain_init_b2_1e-6', pool, 's0 = [1 1];', 's0 = [1, 1 - 1e-6];', ...
    'initial: the reserve starting at 1 - 1e-6');
M = add(M, 'chain_output_b2', pool, 'F = s(:, 1, :);', 'F = s(:, 2, :);', ...
    'output: the factor returned as the reserve b2 (the unpacked synaptic output; rhs and linearize keep b1)');
M = add(M, 'chain_output_b1b2', pool, 'F = s(:, 1, :);', 'F = s(:, 1, :) .* s(:, 2, :);', ...
    'output: the factor returned as b1 b2, the product''s');
M = add(M, 'chain_depression_b2', pool, 'D = b(:, 1, :);', 'D = b(:, 2, :);', ...
    'depression (what std_route_factor returns for a chain route): b2');
M = add(M, 'chain_depression_b1b2', pool, 'D = b(:, 1, :);', 'D = prod(b, 2);', ...
    'depression (std_route_factor): prod(b), what display code drew before the chain');

%% The registry
M = add(M, 'chain_registry_product', registry, ...
    'model = route_pool();', ...
    ['model = route_product(); c = model.compile; ' ...
     'model.compile = @(s, f, o) c(rmfield(s, {''model'', ''n2''}), f, o);'], ...
    ['the registry hands a chain route the product model: nothing throws, the route runs as a ' ...
     'two-component product with the chain''s time constants']);

%% SRNNCellTypePairs: where the class places a coupled route's numbers
M = add(M, 'chain_j_ss_transposed', pairs, ...
    'J(row_s, row_s) = sparse(repmat(at, 1, ns), repelem(at, 1, ns), ...', ...
    'J(row_s, row_s) = sparse(repelem(at, 1, ns), repmat(at, 1, ns), ...', ...
    ['compute_Jacobian_fast: entry (m, k) of A written at (k, m). Invisible for a diagonal A, so the ' ...
     'post-refactor list could not hold it; the chain''s 2 x 2 is not symmetric']);
jt_full = 'Zs = reshape(sum(A .* reshape(Ys, npre, 1, ns, K), 3), npre, ns, K);';
M = add(M, 'chain_jt_full_transposed', pairs, jt_full, ...
    'Zs = reshape(sum(permute(A, [1 3 2]) .* reshape(Ys, npre, 1, ns, K), 3), npre, ns, K);', ...
    'jacobian_times, the full-A branch: A applied transposed');
M = add(M, 'chain_jt_full_1e-9', pairs, jt_full, ...
    'Zs = (1 + 1e-9) .* reshape(sum(A .* reshape(Ys, npre, 1, ns, K), 3), npre, ns, K);', ...
    'jacobian_times, the full-A branch scaled by 1 + 1e-9 (the branch no case of the anchor reaches)');
M = add(M, 'chain_jt_full_offdiag_1e-9', pairs, jt_full, ...
    ['Zs = reshape(sum(A .* reshape(Ys, npre, 1, ns, K), 3), npre, ns, K); ' ...
     'Zs(:, 1, :) = Zs(:, 1, :) + 1e-9 .* A(:, 1, ns) .* Ys(:, ns, :);'], ...
    'jacobian_times, the full-A branch: the off-diagonal term A(1, ns) alone scaled by 1 + 1e-9');
M = add(M, 'chain_idx_b1_b2_swapped', pairs, ...
    'params.route{pre, post}.idx = [layout.b{pre, post}, layout.g{pre, post}];', ...
    ['params.route{pre, post}.idx = [layout.b{pre, post}, layout.g{pre, post}]; ' ...
     'if pair.std_chain(pre, post), h = numel(layout.b{pre, post}) / 2; ' ...
     'params.route{pre, post}.idx(1:2 * h) = layout.b{pre, post}([h + 1:2 * h, 1:h]); end'], ...
    ['a chain route''s state indices: the rows of b1 and of b2 exchanged (the same rows, so nothing ' ...
     'throws; the route reads the reserve as the releasable pool)']);
M = add(M, 'chain_unpack_b_reversed', pairs, ...
    'b_named.(pre_name).(post_name) = s(:, 1:P.n_b, :);', ...
    'b_named.(pre_name).(post_name) = s(:, P.n_b:-1:1, :);', ...
    'unpack_and_compute_states: the b columns returned in reverse order (b2 where display code expects b1)');
end

function M = add(M, name, file, find_text, replace_text, what)
M(end + 1) = struct('name', name, 'file', file, 'find', find_text, 'replace', replace_text, 'what', what);
end
