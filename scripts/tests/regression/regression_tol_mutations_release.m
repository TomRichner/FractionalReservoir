function M = regression_tol_mutations_release(which_list)
% REGRESSION_TOL_MUTATIONS_RELEASE The deliberate errors in the release noise that the tolerance tier's release suite must catch.
%
%   M = regression_tol_mutations_release()            % the list
%   G = regression_tol_mutations_release('groups')    % leaf groups for the harness
%   rows = regression_tol_mutate(M, 'reference', 'release', 'groups', G);
%
% DATA FOR regression_tol_mutate (FD-027; docs/Plan_release_noise.md,
% section 4). The release suite of the tolerance tier (regression_tol_run,
% suite 'release'; reference scripts/tests/fixtures/regression_tol_release.mat)
% is the gate for later work on the release noise. Each entry is one
% minimal one-site edit: a file, a text that occurs exactly once in it,
% and its replacement. THE TEXT IS TIED TO THE CODE AS IT STANDS at the
% commit that added this file.
%
% A SHORT, TARGETED LIST, one per kind of site (CLAUDE.md, "When to run
% mutation checks"): the release noise is new arithmetic in the dynamics
% and the Jacobian, so it has one; it is run once, and re-run only for the
% entries a later change of the reference affects.
%
% THE MECHANISM (route_model, "RELEASE NOISE"). Over a step a presynaptic
% neuron's release drive is r dt + dR. Its mean r_s is a leak in the
% drift: the release drive rho = r + r_s in the depletion terms of a
% route's pools and in theta = F rho, and nowhere else (facilitation and
% the calcium trace follow the rate). The rest, dRc = dR - r_s dt, is a
% kick after each step: pools by their exact solution, and the amount
% released into x as W dTheta / tau_d.
%
% THE ERRORS. The fourteen of the plan, in its order:
%    1 leak_sign_pool          the leak's sign in the pool's release term (rhs)
%    2 leak_missing_theta      the leak missing from theta in dynamics_fast
%    3 leak_missing_jtimes     ... missing from jacobian_times only
%    4 leak_in_facilitation    the leak wrongly in the facilitation equation
%    5 leak_on_product_g       the leak on the product model's facilitation columns
%    6 leak_1e6_linearize      r_s + 1e-6 in route_pool's linearize only
%    7 steady_no_leak          steady_state without the leak
%    8 kick_linear             dTheta = F dRc in place of the exact release
%    9 kick_sign               the kick's sign: the pool grows
%   10 kick_one_tau            one tau_rel for every pool of a product route
%   11 kick_no_tau_d           the kick into x without 1/tau_d
%   12 increment_uncentered    the increments not centered on r_s dt
%   13 increment_wrong_step    the kick of step j reading another step's increment
%   14 shape_without_dt        the gamma shape without the step
% two for the reservoir's arithmetic (step N2):
%   15 filter_coefficient      a coefficient of filter_release off by 1e-6 of itself
%   16 released_wrong_step     `released` for several steps reading the first step's pool
% and four more sites of kinds the sixteen do not cover:
%   17 leak_missing_jacobian   the leak missing from the ASSEMBLED Jacobian only
%   18 lean_uncentered         the lean path's own centering (segment_noise)
%   19 kick_without_g          release probability not scaling the kick
%   20 kick_relative_step      sde_fixed_step asking for the kick by the step's
%                              index in the call, not its absolute index
%
% See also: regression_tol_mutate, regression_tol_check, regression_tol_run,
%           route_model, route_pool, route_product, release_increments
arguments
    which_list (1,:) char {mustBeMember(which_list, {'list', 'groups'})} = 'list'
end
if strcmp(which_list, 'groups')
    % What kind of leaf saw the error (first match wins; the overridden
    % groups of regression_tol_settings first), for the suite's keys.
    M = { ...
        'ov_orth_defect',   '(^|\.)orth_defect_max$'; ...
        'ov_fd_jacobian',   '(^|\.)finite_difference_J$'; ...
        'ov_mc',            '^stable\.mc\.\w+\.(MC|R2)$'; ...
        'pw_filter',        '^pointwise\.filter\.'; ...
        'pw_kick',          '^pointwise\..*\.release\.(kick_S|kicked\.|run_kick)'; ...
        'pw_steady',        '^pointwise\..*\.release\.steady\.'; ...
        'pw_increments',    '^pointwise\..*\.release\.(run_dRc|dR)$'; ...
        'pw_view',          '^pointwise\..*\.view\.'; ...
        'pw_dS',            '^pointwise\..*\.dS$'; ...
        'pw_J',             '^pointwise\..*\.J(\{\d+\}|#size)$'; ...
        'pw_JY',            '^pointwise\..*\.JY$'; ...
        'pw_rate_theta',    '^pointwise\..*\.(rate|synaptic_output)\.'; ...
        'pw_other',         '^pointwise\.'; ...
        'st_trajectory',    '^stable\.model\.\w+\.(S0|S_kept|t_kept|W|plot_data\.|tau_a_clipped)'; ...
        'st_release',       '^stable\.model\.\w+\.(release|kicked)\.'; ...
        'st_topk',          '^stable\.model\.\w+\.(lya_results|lya_summary)\.'; ...
        'st_gain',          '^stable\.extra\.transient_gain\.'; ...
        'st_benettin',      '^stable\.estimators\.\w+\.benettin\.'; ...
        'st_sweep',         '^stable\.sweep\.'; ...
        'st_mc',            '^stable\.mc\.'; ...
        'st_other',         '^stable\.'};
    return;
end
pairs = 'src/model/SRNNCellTypePairs.m';
esn = 'src/model/SRNN_ESN_reservoir.m';
pool = 'src/model/routes/route_pool.m';
product = 'src/model/routes/route_product.m';
increments = 'src/model/integrators/release_increments.m';
sde = 'src/model/integrators/sde_fixed_step.m';

rows = { ...
    'leak_sign_pool', pool, ...
        '    release = b1 .* drive ./ P.tau_rel;', ...
        '    release = b1 .* (drive - 2 .* P.release.rate) ./ P.tau_rel;', ...
        'the leak enters the pool''s release term with the wrong sign (a pool without release probability)'; ...
    'leak_missing_theta', pairs, ...
        'params.W(post_idx, pre_idx) * (F .* drive);', ...
        'params.W(post_idx, pre_idx) * (F .* pre_rate);', ...
        'dynamics_fast forms theta = F r: the leak is missing from the synaptic output'; ...
    'leak_missing_jtimes', pairs, ...
        'dtheta = dtheta + drive .* reshape(sum(Fs .* Ys, 2), npre, K);', ...
        'dtheta = dtheta + pre_rate .* reshape(sum(Fs .* Ys, 2), npre, K);', ...
        'jacobian_times alone forms d(theta)/ds = r Fs: the leak is missing from one Jacobian function'; ...
    'leak_in_facilitation', pool, ...
        '    dg = (1 - g) ./ P.tau_dec + (P.G - g) .* r ./ P.tau_fac;', ...
        '    dg = (1 - g) ./ P.tau_dec + (P.G - g) .* drive ./ P.tau_fac;', ...
        'release probability is driven by the release drive, not the rate (a route without a calcium trace)'; ...
    'leak_on_product_g', product, ...
        '[repmat(double(opts.release_rate), 1, P.n_b), zeros(1, P.n_g)]);', ...
        '[repmat(double(opts.release_rate), 1, P.n_b), repmat(double(opts.release_rate), 1, P.n_g)]);', ...
        'the product model''s leak is on its facilitation columns too'; ...
    'leak_1e6_linearize', pool, ...
        ['drive = r + P.release.rate;' newline 'npre = size(s, 1);'], ...
        ['drive = r + P.release.rate + 1e-6;' newline 'npre = size(s, 1);'], ...
        'route_pool''s linearize alone computes with r_s + 1e-6'; ...
    'steady_no_leak', pool, ...
        ['rho = r + P.release.rate;' newline 'if P.has_g'], ...
        ['rho = r;' newline 'if P.has_g'], ...
        'route_pool''s steady_state without the leak'; ...
    'kick_linear', pool, ...
        'dTheta = -P.tau_rel .* b1 .* expm1(-used);', ...
        'dTheta = b1 .* dRc;', ...
        'the kick releases F dRc, not the exact amount the pool lost'; ...
    'kick_sign', pool, ...
        's(:, 1) = b1 .* exp(-used);', ...
        's(:, 1) = b1 .* exp(used);', ...
        'the kick''s sign: a release fills the pool'; ...
    'kick_one_tau', product, ...
        's(:, 1:P.n_b) = s(:, 1:P.n_b) .* exp(-dRc ./ P.tau_drive(:, 1:P.n_b));', ...
        's(:, 1:P.n_b) = s(:, 1:P.n_b) .* exp(-dRc ./ P.tau_drive(:, 1));', ...
        'every pool of a product route is kicked with the first pool''s tau_rel'; ...
    'kick_no_tau_d', pairs, ...
        'S(rows) = S(rows) + to_x(params.type_indices{post}, post) ./ params.tau_d;', ...
        'S(rows) = S(rows) + to_x(params.type_indices{post}, post);', ...
        'the released amount reaches x without the factor 1/tau_d'; ...
    'increment_uncentered', pairs, ...
        ['''SRNNCellTypePairs'') ...' newline '                    - rate .* (1 / obj.fs);'], ...
        ['''SRNNCellTypePairs'') ...' newline '                    - 0 .* rate .* (1 / obj.fs);'], ...
        'build_noise does not take the mean r_s dt out of the increments (the leak is then counted twice)'; ...
    'increment_wrong_step', pairs, ...
        '@(S, j) SRNNCellTypePairs.release_kick(S, dRc(:, j), params);', ...
        '@(S, j) SRNNCellTypePairs.release_kick(S, dRc(:, max(j - 1, 1)), params);', ...
        'the kick after step j uses the increment of step j - 1'; ...
    'shape_without_dt', increments, ...
        'shape = rate(noisy) .^ 2 .* dt ./ sigma(noisy) .^ 2;', ...
        'shape = rate(noisy) .^ 2 ./ sigma(noisy) .^ 2;', ...
        'the gamma shape without the step: r_s^2 / sigma^2'; ...
    'filter_coefficient', esn, ...
        'c0 = -expm1(-dt ./ tau) - c1;', ...
        'c0 = -expm1(-dt ./ tau) - c1 .* (1 + 1e-6);', ...
        'filter_release''s c0 computed from c1 (1 + 1e-6)'; ...
    'released_wrong_step', pool, ...
        'dTheta = P.tau_rel .* s_after(:, 1, :) .* expm1(dRc ./ P.tau_rel);', ...
        'dTheta = P.tau_rel .* s_after(:, 1, 1) .* expm1(dRc ./ P.tau_rel);', ...
        '`released` for several steps reads the pool after the FIRST step for all of them'; ...
    'leak_missing_jacobian', pairs, ...
        'to_theta = drive .* Fs;', ...
        'to_theta = pre_rate .* Fs;', ...
        'compute_Jacobian_fast alone forms d(theta)/ds = r Fs'; ...
    'lean_uncentered', esn, ...
        'numel(obj.t_ex) - 1, ''SRNNCellTypePairs'') - rate .* (1 / obj.fs);', ...
        'numel(obj.t_ex) - 1, ''SRNNCellTypePairs'') - 0 .* rate .* (1 / obj.fs);', ...
        'the lean memory path''s increments (segment_noise) are not centered'; ...
    'kick_without_g', pool, ...
        'dRc = s(:, P.n_b + 1) .* dRc;             % release probability scales the drive', ...
        'dRc = 1 .* dRc;', ...
        'release probability does not scale the kick'; ...
    'kick_relative_step', sde, ...
        'y = noise.kick(y, j);', ...
        'y = noise.kick(y, k);', ...
        'the integrator asks for the kick by the step''s index within the call, not its absolute index'};
M = cell2struct(rows, {'name', 'file', 'find', 'replace', 'what'}, 2)';
end
