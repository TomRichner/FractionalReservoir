function M = regression_tol_mutations_post_refactor(which_list)
% REGRESSION_TOL_MUTATIONS_POST_REFACTOR The deliberate errors the tolerance tier must catch, for the model class AFTER the route-interface refactor.
%
%   M = regression_tol_mutations_post_refactor()         % the list
%   M = regression_tol_mutations_post_refactor('scan')   % the detection-limit scan
%   rows = regression_tol_mutate(M);
%
% DATA FOR regression_tol_mutate (FD-021; Plan A, step 0d). The successor
% of regression_tol_mutations_pre_refactor: the same KINDS of error, at
% the sites they have now that product depression and today's
% facilitation sit behind the route interface (src/model/routes), plus
% the errors that structure makes possible. Each entry is one minimal
% one-site edit: a file, a text that occurs exactly once in it, and its
% replacement. THE TEXT IS TIED TO THE CODE AS IT STANDS at the commit
% that added this file; when the code is rewritten again,
% regression_tol_mutate refuses an entry whose text is gone, and the list
% is written again beside this one.
%
% Fields: name, file, find, replace, what, origin:
%   'carried'  an error of the pre-refactor list, at its new site (the
%              name is kept where the error is the same)
%   'new'      an error the route interface makes possible
%
% WHAT MOVED WHERE, for reading the two lists side by side.
%   - A route's parameters are compiled by its model (route_product:
%     compile). The parameter mutations are there. P carries the values
%     the arithmetic reads PER NEURON, beside the nominal rows that the
%     tier's parameter view reads through route_fields; so there are now
%     errors the view cannot see (P_tau_rest_1e-6 and its two siblings).
%   - Depression and facilitation are one equation in route_product's rhs
%     (rest term and drive term), so recovery_sign and release_1e-6 act
%     on both; fac_buildup_sign singles facilitation out by its target.
%   - The six Jacobian blocks that depression had and the six that
%     facilitation had are ONE set on the route's state s: (s, a), (s, s),
%     (s, x), (x, s). j_drop_s_* and jt_s_* are their mutations. The
%     entries of the linearisation itself (A, B, F, Fs) are written once,
%     in route_product's linearize, and read by both Jacobian routines: an
%     error there (lin_*) moves J and JY together and leaves dS alone.
%   - jacobian_times applies A by its diagonal for a model that states a
%     diagonal coupling (every route today). Its other branch, the full
%     per-neuron product, is NOT REACHED by any case of the tier, so no
%     mutation of it is in this list: the tier could not catch one. It is
%     covered by check 4 of test_route_models.
%   - The same holds for active_routes' recompile (reached only when a
%     caller switches params.std_zero_floor after get_params) and for
%     product_of_others with three or more columns: no case of the tier
%     has them; test_SRNNCellTypePairs / test_jacobian_times and
%     test_route_models do.
%
% NAMING. j_drop_<row>_<col> zeroes one block of compute_Jacobian_fast
% (row = which derivative, col = which state; s = a route's state).
% jt_<row>_<col> scales the matching term of jacobian_times by 1 + 1e-9,
% so that the matrix-free product and the assembled Jacobian disagree in
% that block only. lin_<what> is an error in route_product's linearize.
%
% THE SCAN repeats three of the errors (the depression tau_rec, the first
% SFA rung, the (x, s) term of jacobian_times) at 1e-4, 1e-6, 1e-8, 1e-10
% and 1e-12 relative.
%
% See also: regression_tol_mutate, regression_tol_mutations_pre_refactor,
%           regression_tol_check, route_product
arguments
    which_list (1,:) char {mustBeMember(which_list, {'list', 'scan'})} = 'list'
end
pairs = 'src/model/SRNNCellTypePairs.m';
product = 'src/model/routes/route_product.m';
registry = 'src/model/routes/route_model.m';
esn = 'src/model/SRNN_ESN_reservoir.m';
M = struct('name', {}, 'file', {}, 'find', {}, 'replace', {}, 'what', {}, 'origin', {});

tau_rec_line = 'nominal.tau_rec = positive_row(std_cfg.tau_rec, [], ''tau_rec'', ''STD'', opts.label, err_id);';
tau_a_line = 'params.c = obj.c;';
tau_a_patch = ['params.c = obj.c; for q = 1:obj.n_cellTypes, if ~isempty(params.tau_a_matrix{q}), ' ...
    'params.tau_a_matrix{q}(:, 1) = params.tau_a_matrix{q}(:, 1) .* (1 + %s); end, end'];
jt_x_s_line = 'dtheta = dtheta + pre_rate .* reshape(sum(Fs .* Ys, 2), npre, K);';

if strcmp(which_list, 'scan')
    sizes = {'1e-4', '1e-6', '1e-8', '1e-10', '1e-12'};
    for k = 1:numel(sizes)
        s = sizes{k};
        tag = strrep(s, '-', 'm');
        M = add(M, ['scan_tau_rec_' tag], product, tau_rec_line, ...
            sprintf('%s nominal.tau_rec = nominal.tau_rec .* (1 + %s);', tau_rec_line, s), ...
            sprintf('every depression tau_rec off by %s relative', s), 'carried');
        M = add(M, ['scan_tau_a_' tag], pairs, tau_a_line, sprintf(tau_a_patch, s), ...
            sprintf('the first SFA rung of every neuron off by %s relative', s), 'carried');
        M = add(M, ['scan_jt_x_s_' tag], pairs, jt_x_s_line, ...
            sprintf('dtheta = dtheta + (1 + %s) .* pre_rate .* reshape(sum(Fs .* Ys, 2), npre, K);', s), ...
            sprintf('jacobian_times: the (x, s) term scaled by 1 + %s (was scan_jt_x_b)', s), 'carried');
    end
    return;
end

%% Parameters, where they are compiled (route_product: compile; get_params)
M = add(M, 'tau_rec_1e-6', product, tau_rec_line, ...
    [tau_rec_line ' nominal.tau_rec = nominal.tau_rec .* (1 + 1e-6);'], ...
    'every depression tau_rec off by 1e-6 relative (nominal, and so the per-neuron values too)', 'carried');
M = add(M, 'tau_rel_1e-6', product, ...
    'if isfield(std_cfg, ''combine'') && ~isempty(std_cfg.combine)', ...
    'nominal.tau_rel = nominal.tau_rel .* (1 + 1e-6); if isfield(std_cfg, ''combine'') && ~isempty(std_cfg.combine)', ...
    'every depression tau_rel off by 1e-6 relative', 'carried');
M = add(M, 'tau_a_rung_1e-6', pairs, tau_a_line, sprintf(tau_a_patch, '1e-6'), ...
    'the first SFA rung of every neuron off by 1e-6 relative, in the tau_a_matrix the physics reads', 'carried');
M = add(M, 'c_eff_no_K', pairs, ...
    'params.c_eff = obj.c ./ max(1, obj.n_a);', ...
    'params.c_eff = obj.c;', ...
    'c_eff: the division by the number of SFA timescales removed', 'carried');
M = add(M, 'G_1e-6', product, ...
    'if any(nominal.G < 1)', ...
    'nominal.G = nominal.G .* (1 + 1e-6); if any(nominal.G < 1)', ...
    'every facilitation ceiling G off by 1e-6 relative', 'carried');
M = add(M, 'tau_fac_1e-6', product, ...
    'nominal.tau_fac = positive_row(stf_cfg.tau_fac, L, ''tau_fac'', ''STF'', opts.label, err_id);', ...
    ['nominal.tau_fac = positive_row(stf_cfg.tau_fac, L, ''tau_fac'', ''STF'', opts.label, err_id); ' ...
     'nominal.tau_fac = nominal.tau_fac .* (1 + 1e-6);'], ...
    'every facilitation tau_fac off by 1e-6 relative', 'carried');
M = add(M, 'tau_dec_1e-6', product, ...
    'L = numel(nominal.tau_dec);', ...
    'nominal.tau_dec = nominal.tau_dec .* (1 + 1e-6); L = numel(nominal.tau_dec);', ...
    'every facilitation tau_dec off by 1e-6 relative', 'carried');
M = add(M, 'tau_d_1e-6', pairs, ...
    'params.tau_d = obj.tau_d;', ...
    'params.tau_d = obj.tau_d .* (1 + 1e-6);', ...
    'tau_d off by 1e-6 relative in params only: a parameter error the parameter view cannot see', 'carried');
M = add(M, 'route_scale_not_folded', pairs, ...
    'if any(pair.scale(:) ~= 1)', ...
    'if false', ...
    'the route scale not folded into params.W', 'carried');
M = add(M, 'tau_rec_I_to_E_param_1e-6', product, tau_rec_line, ...
    [tau_rec_line ' nominal.tau_rec = nominal.tau_rec .* (1 + 1e-6 * strcmp(opts.label, ''I->E''));'], ...
    ['the I->E route''s tau_rec alone off by 1e-6, as a PARAMETER: makes the reservoir refuse the synaptic ' ...
     'readout, kept to record what a thrown case looks like beside value failures'], 'carried');
M = add(M, 'P_tau_rest_1e-6', product, ...
    'P.tau_rest  = per_neuron([nominal.tau_rec, nominal.tau_dec], opts.npre);', ...
    'P.tau_rest  = per_neuron([nominal.tau_rec, nominal.tau_dec], opts.npre) .* (1 + 1e-6);', ...
    ['the PER-NEURON tau_rest (tau_rec, tau_dec) off by 1e-6 with the nominal rows right: the values the ' ...
     'arithmetic reads no longer are the ones the parameter view reads, so the view cannot see this'], 'new');
M = add(M, 'P_tau_drive_1e-6', product, ...
    'P.tau_drive = per_neuron([nominal.tau_rel, nominal.tau_fac], opts.npre);', ...
    'P.tau_drive = per_neuron([nominal.tau_rel, nominal.tau_fac], opts.npre) .* (1 + 1e-6);', ...
    'the per-neuron tau_drive (tau_rel, tau_fac) off by 1e-6 with the nominal rows right', 'new');
M = add(M, 'P_target_1e-6', product, ...
    'P.target    = per_neuron([zeros(1, P.n_b), nominal.G], opts.npre);', ...
    'P.target    = per_neuron([zeros(1, P.n_b), nominal.G], opts.npre) .* (1 + 1e-6);', ...
    'the per-neuron target (the facilitation ceiling G; depression''s 0 is unchanged) off by 1e-6, nominal right', 'new');
M = add(M, 'P_one_neuron_tau_rest_1e-6', product, ...
    'P.tau_rest  = per_neuron([nominal.tau_rec, nominal.tau_dec], opts.npre);', ...
    ['P.tau_rest  = per_neuron([nominal.tau_rec, nominal.tau_dec], opts.npre); ' ...
     'P.tau_rest(1, :) = P.tau_rest(1, :) .* (1 + 1e-6);'], ...
    'ONE neuron''s row of the per-neuron tau_rest off by 1e-6 (the first neuron of every presynaptic type)', 'new');

%% The route's equations (route_product: rhs) and the class's use of them
M = add(M, 'recovery_sign', product, ...
    'ds = (1 - s) ./ P.tau_rest + ((P.target - s) .* r) ./ P.tau_drive;', ...
    'ds = -(1 - s) ./ P.tau_rest + ((P.target - s) .* r) ./ P.tau_drive;', ...
    'rhs: the sign of the rest term flipped (depression recovery; also facilitation decay, the same term now)', 'carried');
M = add(M, 'recovery_I_to_E_1e-6', pairs, ...
    'dS(R.idx) = ds;', ...
    'dS(R.idx) = ds .* (1 + 1e-6 * (pre == 2 && post == 1));', ...
    ['dynamics_fast: the state derivative of the I->E route alone scaled by 1 + 1e-6 (one route, in the ' ...
     'arithmetic, so no parameter differs between routes and nothing throws)'], 'carried');
M = add(M, 'release_1e-6', product, ...
    'ds = (1 - s) ./ P.tau_rest + ((P.target - s) .* r) ./ P.tau_drive;', ...
    'ds = (1 - s) ./ P.tau_rest + (1 + 1e-6) .* ((P.target - s) .* r) ./ P.tau_drive;', ...
    'rhs: the drive term scaled by 1 + 1e-6 (depression release; also facilitation build-up)', 'carried');
M = add(M, 'fac_buildup_sign', product, ...
    'ds = (1 - s) ./ P.tau_rest + ((P.target - s) .* r) ./ P.tau_drive;', ...
    'ds = (1 - s) ./ P.tau_rest + ((1 - 2 .* (P.target > 0)) .* (P.target - s) .* r) ./ P.tau_drive;', ...
    'rhs: the sign of the drive term flipped for facilitation only (the columns whose target is G)', 'carried');
M = add(M, 'sfa_drive_1e-6', pairs, ...
    'dS(layout.a{q}) = (rate(params.type_indices{q}) - a{q}) ./ params.tau_a_matrix{q};', ...
    'dS(layout.a{q}) = ((1 + 1e-6) .* rate(params.type_indices{q}) - a{q}) ./ params.tau_a_matrix{q};', ...
    'dynamics_fast: the rate driving SFA scaled by 1 + 1e-6', 'carried');
M = add(M, 'input_1e-6', pairs, ...
    'dS(layout.x) = (-x + recurrent + u) ./ params.tau_d;', ...
    'dS(layout.x) = (-x + recurrent + (1 + 1e-6) .* u) ./ params.tau_d;', ...
    'dynamics_fast: the external input scaled by 1 + 1e-6', 'carried');
M = add(M, 'theta_1e-6', pairs, ...
    'params.W(post_idx, pre_idx) * (F .* pre_rate);', ...
    'params.W(post_idx, pre_idx) * ((1 + 1e-6) .* F .* pre_rate);', ...
    'dynamics_fast: every route''s synaptic output F .* rate scaled by 1 + 1e-6 where it enters dx/dt', 'new');
M = add(M, 'geomean_plain_product_dS', product, ...
    'F = output(s, P);', ...
    'Q = P; Q.geomean = false; F = output(s, Q);', ...
    'rhs only: the depression factor left as the plain product on a geomean route', 'carried');
M = add(M, 'zero_floor_off_dS', product, ...
    'F = output(s, P);', ...
    'Q = P; Q.zero_floor = false; F = output(s, Q);', ...
    'rhs only: the zero floor not applied', 'carried');
M = add(M, 'output_no_facilitation', product, ...
    'F = depression(prod(s(:, 1:P.n_b, :), 2), P) .* prod(s(:, P.n_b + 1:end, :), 2);', ...
    'F = depression(prod(s(:, 1:P.n_b, :), 2), P);', ...
    ['output: the facilitation factor dropped (was unpack_no_facilitation; output now serves the right-hand ' ...
     'side and the unpacking, so both lose it; the linearisation keeps it)'], 'carried');

%% The combine and the zero floor (route_product)
M = add(M, 'p_min_1e-6', product, ...
    'P.p_min = combine(prod(at_ceiling.s(:, 1:P.n_b), 2), P);', ...
    'P.p_min = combine(prod(at_ceiling.s(:, 1:P.n_b), 2), P) .* (1 + 1e-6);', ...
    'the zero floor''s p_min off by 1e-6 relative', 'carried');
M = add(M, 'geomean_gain_omitted', product, ...
    'dD_dP = D ./ (P.n_b .* P_b);', ...
    'dD_dP = ones(size(P_b));', ...
    ['linearize: the geomean gain dD/dP omitted. One site now serves both Jacobian routines (was ' ...
     'geomean_gain_omitted_J and _jt), so J and JY are wrong together'], 'carried');
M = add(M, 'floor_gain_omitted', product, ...
    'dD_dP = floor_gain .* dD_dP;', ...
    'dD_dP = 1 .* dD_dP;', ...
    'linearize: the zero floor''s slope 1/(1 - p_min) omitted from dF/db', 'new');
M = add(M, 'geomean_exponent_1e-6', product, ...
    'D = P_b .^ (1 / P.n_b);', ...
    'D = P_b .^ ((1 + 1e-6) / P.n_b);', ...
    'the geomean exponent 1/M off by 1e-6 relative', 'new');

%% The activation
M = add(M, 'phi_prime_1e-6', pairs, ...
    'dy = 4 .* value .* (1 - value);', ...
    'dy = 4 .* (1 + 1e-6) .* value .* (1 - value);', ...
    'the logistic derivative off by 1e-6: every Jacobian block wrong alike in J and jacobian_times, dS untouched', 'carried');

%% route_product: linearize. Read by BOTH Jacobian routines, so J and JY move together
M = add(M, 'lin_A_last_1e-9', product, ...
    'A = reshape(A, npre, ns, ns);', ...
    'A = reshape(A, npre, ns, ns); A(:, end, end) = A(:, end, end) .* (1 + 1e-9);', ...
    'linearize: the last state variable''s own entry of A off by 1e-9 (b_2 on a two-component route, the last g with facilitation)', 'new');
M = add(M, 'lin_A_first_dropped', product, ...
    'A = reshape(A, npre, ns, ns);', ...
    'A = reshape(A, npre, ns, ns); A(:, 1, 1) = 0;', ...
    'linearize: the first state variable''s own entry of A dropped', 'new');
M = add(M, 'lin_A_spurious_coupling_1e-6', product, ...
    'A = reshape(A, npre, ns, ns);', ...
    'A = reshape(A, npre, ns, ns); if ns > 1, A(:, 1, ns) = 1e-6; end', ...
    ['linearize: an off-diagonal entry of A that should be zero set to 1e-6, AGAINST what P.coupling states. ' ...
     'The assembled Jacobian takes all of A; jacobian_times, told A is diagonal, never reads the entry'], 'new');
M = add(M, 'lin_B_1e-9', product, ...
    'B = (P.target - s) ./ P.tau_drive;', ...
    'B = (1 + 1e-9) .* (P.target - s) ./ P.tau_drive;', ...
    'linearize: B = d(ds)/dr off by 1e-9 (the (s, x) and (s, a) blocks of both routines)', 'new');
M = add(M, 'lin_B_facilitation_dropped', product, ...
    'B = (P.target - s) ./ P.tau_drive;', ...
    'B = (P.target == 0) .* (P.target - s) ./ P.tau_drive;', ...
    'linearize: B dropped for the facilitation columns (was j_drop_g_x and j_drop_g_a together)', 'carried');
M = add(M, 'lin_F_1e-9', product, ...
    '[F, dD_dP] = depression(prod(s, 2), P);', ...
    '[F, dD_dP] = depression(prod(s, 2), P); F = F .* (1 + 1e-9);', ...
    'linearize: the output factor F off by 1e-9 on routes without facilitation (the recurrent (x, x) and (x, a) blocks)', 'new');
M = add(M, 'lin_Fs_1e-9', product, ...
    'Fs = dD_dP .* product_of_others(s);', ...
    'Fs = (1 + 1e-9) .* dD_dP .* product_of_others(s);', ...
    'linearize: dF/ds off by 1e-9 on routes without facilitation (the (x, s) block)', 'new');
M = add(M, 'lin_Fs_g_1e-9', product, ...
    'Fs = [(dD_dP .* facilitation) .* product_of_others(b), D .* product_of_others(g)];', ...
    'Fs = [(dD_dP .* facilitation) .* product_of_others(b), (1 + 1e-9) .* D .* product_of_others(g)];', ...
    'linearize: dF/dg off by 1e-9 (was jt_x_g, now in both routines)', 'carried');
M = add(M, 'lin_Fs_b_with_g_1e-9', product, ...
    'Fs = [(dD_dP .* facilitation) .* product_of_others(b), D .* product_of_others(g)];', ...
    'Fs = [(1 + 1e-9) .* (dD_dP .* facilitation) .* product_of_others(b), D .* product_of_others(g)];', ...
    'linearize: dF/db off by 1e-9 on routes that also carry facilitation', 'new');
M = add(M, 'lin_others_not_swapped', product, ...
    'Q = v(:, [2 1]);', ...
    'Q = v;', ...
    'linearize: with two components, d(b_1 b_2)/db_1 taken as b_1 where it is b_2', 'new');

%% compute_Jacobian_fast: one block dropped per mutation
M = add(M, 'j_drop_a_x', pairs, ...
    'J(row_a, row_x) = sparse((1:numel(row_a))'', ...', ...
    'J(row_a, row_x) = 0 .* sparse((1:numel(row_a))'', ...', ...
    'compute_Jacobian_fast: the (a, x) block dropped', 'carried');
M = add(M, 'j_drop_a_a_coupling', pairs, ...
    'J(row_a, row_a) = diag_block + coupling;', ...
    'J(row_a, row_a) = diag_block;', ...
    'compute_Jacobian_fast: the coupling part of the (a, a) block dropped', 'carried');
M = add(M, 'j_drop_a_a_diagonal', pairs, ...
    'J(row_a, row_a) = diag_block + coupling;', ...
    'J(row_a, row_a) = coupling;', ...
    'compute_Jacobian_fast: the diagonal part of the (a, a) block dropped', 'carried');
M = add(M, 'j_drop_s_a', pairs, ...
    'J(row_s, row_a) = kron(sparse(ones(1, na)), stack);', ...
    'J(row_s, row_a) = 0 .* kron(sparse(ones(1, na)), stack);', ...
    'compute_Jacobian_fast: the (s, a) block dropped (was j_drop_b_a and j_drop_g_a)', 'carried');
M = add(M, 'j_drop_s_s', pairs, ...
    'J(row_s, row_s) = sparse(repmat(at, 1, ns), repelem(at, 1, ns), ...', ...
    'J(row_s, row_s) = 0 .* sparse(repmat(at, 1, ns), repelem(at, 1, ns), ...', ...
    'compute_Jacobian_fast: the (s, s) block dropped (was j_drop_b_b and j_drop_g_g)', 'carried');
M = add(M, 'j_drop_s_x', pairs, ...
    'J(row_s, row_x) = sparse(at(:), repmat(pre_idx(:), ns, 1), ...', ...
    'J(row_s, row_x) = 0 .* sparse(at(:), repmat(pre_idx(:), ns, 1), ...', ...
    'compute_Jacobian_fast: the (s, x) block dropped (was j_drop_b_x and j_drop_g_x)', 'carried');
M = add(M, 'j_drop_x_a', pairs, ...
    'block = -params.c_eff(pre) .* rate_block;', ...
    'block = 0 .* rate_block;', ...
    'compute_Jacobian_fast: the (x, a) block dropped', 'carried');
M = add(M, 'j_drop_x_s', pairs, ...
    'J(row_x(post_idx), row_s) = (W_block * D) ./ params.tau_d;', ...
    'J(row_x(post_idx), row_s) = 0 .* (W_block * D) ./ params.tau_d;', ...
    'compute_Jacobian_fast: the (x, s) block dropped (was j_drop_x_b and j_drop_x_g)', 'carried');
M = add(M, 'j_drop_x_x_rate_block', pairs, ...
    'J(row_x(post_idx), row_x(pre_idx)) + rate_block ./ params.tau_d;', ...
    'J(row_x(post_idx), row_x(pre_idx)) + 0 .* rate_block ./ params.tau_d;', ...
    'compute_Jacobian_fast: the rate_block of (x, x) dropped (the recurrent part; the leak stays)', 'carried');
M = add(M, 'j_drop_x_x_leak', pairs, ...
    'J(row_x, row_x) = spdiags(-ones(n, 1) ./ params.tau_d, 0, n, n);', ...
    'J(row_x, row_x) = sparse(n, n);', ...
    'compute_Jacobian_fast: the leak -1/tau_d of (x, x) dropped', 'carried');
% NOT IN THE LIST, because the tier cannot see it yet: exchanging the rows
% and columns of the (s, s) block (entry (m, k) of A written at (k, m)).
% For a diagonal A, which is all there is today, that changes nothing.
% The first model with a coupling that is not symmetric (the chain) makes
% it a real error, and the chain's own cases have to catch it.

%% jacobian_times: the matching term scaled by 1 + 1e-9
M = add(M, 'jt_a_x', pairs, ...
    'dr = rate_prime(idx) .* Ye{q};', ...
    'dr = rate_prime(idx) .* (Ye{q} + 1e-9 .* Yx(idx, :));', ...
    'jacobian_times: the (a, x) term scaled by 1 + 1e-9', 'carried');
M = add(M, 'jt_a_a_coupling', pairs, ...
    'dr = rate_prime(idx) .* Ye{q};', ...
    'dr = rate_prime(idx) .* (Ye{q} - 1e-9 .* params.c_eff(q) .* reshape(sum(Ya{q}, 2), nq, K));', ...
