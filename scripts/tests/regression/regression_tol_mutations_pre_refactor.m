function M = regression_tol_mutations_pre_refactor(which_list)
% REGRESSION_TOL_MUTATIONS_PRE_REFACTOR The deliberate errors the tolerance tier must catch, for the model class BEFORE the route-interface refactor.
%
%   M = regression_tol_mutations_pre_refactor()         % the list
%   M = regression_tol_mutations_pre_refactor('scan')   % the detection-limit scan
%   rows = regression_tol_mutate(M);
%
% DATA FOR regression_tol_mutate (FD-020; Plan A, step 0c). Each entry is
% one minimal one-site edit: a file, a text that occurs exactly once in it,
% and its replacement. THE TEXT IS TIED TO THE CODE AS IT STOOD at blob
% 2b0118d of src/model/SRNNCellTypePairs.m (commit d87ea6e). After the
% refactor of step 0d (FD-021) most of these texts no longer exist, and
% regression_tol_mutate then refuses the entry rather than running a
% mutation that changes nothing: write the list again for the new code, as
% a new function beside this one, keeping the same ERRORS (the `what`
% column) at their new sites.
%
% Fields: name, file, find, replace, what, origin ('brief' = named in the
% FD-020 brief or the issue; 'added' = added by the worker who ran the
% checks, with the reason in `what`).
%
% NAMING. j_drop_<row>_<col> zeroes one block of compute_Jacobian_fast
% (row = which derivative, col = which state). jt_<row>_<col> scales the
% matching term of jacobian_times by 1 + 1e-9, so that the matrix-free
% product and the assembled Jacobian disagree in that block only.
%
% THE SCAN repeats three of the errors (the depression tau_rec, the first
% SFA rung, the (x, b) term of jacobian_times) at 1e-4, 1e-6, 1e-8, 1e-10
% and 1e-12 relative, to find the smallest size each kind of leaf sees.
%
% In a multi-line `find`, a line break is written with newline and the
% indentation that follows it is the file's own (spaces).
%
% See also: regression_tol_mutate, regression_tol_check
arguments
    which_list (1,:) char {mustBeMember(which_list, {'list', 'scan'})} = 'list'
end
pairs = 'src/model/SRNNCellTypePairs.m';
esn = 'src/model/SRNN_ESN_reservoir.m';
nl = newline;
sp = @(n) repmat(' ', 1, n);
M = struct('name', {}, 'file', {}, 'find', {}, 'replace', {}, 'what', {}, 'origin', {});

if strcmp(which_list, 'scan')
    sizes = {'1e-4', '1e-6', '1e-8', '1e-10', '1e-12'};
    for k = 1:numel(sizes)
        s = sizes{k};
        tag = strrep(s, '-', 'm');
        M = add(M, ['scan_tau_rec_' tag], pairs, ...
            'pair.tau_b_rec{pre, post} = tau_rec;', ...
            sprintf('pair.tau_b_rec{pre, post} = tau_rec .* (1 + %s);', s), ...
            sprintf('every depression tau_rec off by %s relative', s), 'brief');
        M = add(M, ['scan_tau_a_' tag], pairs, ...
            'params.c = obj.c;', ...
            sprintf(['params.c = obj.c; for q = 1:obj.n_cellTypes, if ~isempty(params.tau_a_matrix{q}), ' ...
                'params.tau_a_matrix{q}(:, 1) = params.tau_a_matrix{q}(:, 1) .* (1 + %s); end, end'], s), ...
            sprintf('the first SFA rung of every neuron off by %s relative', s), 'brief');
        M = add(M, ['scan_jt_x_b_' tag], pairs, ...
            '+ (facilitation .* pre_rate) .* dtheta_b ...', ...
            sprintf('+ (1 + %s) .* (facilitation .* pre_rate) .* dtheta_b ...', s), ...
            sprintf('jacobian_times: the (x, b) term scaled by 1 + %s', s), 'brief');
    end
    return;
end

%% Parameters, where they are compiled (compile_synapse_config, get_params)
M = add(M, 'tau_rec_1e-6', pairs, ...
    'pair.tau_b_rec{pre, post} = tau_rec;', ...
    'pair.tau_b_rec{pre, post} = tau_rec .* (1 + 1e-6);', ...
    'every depression tau_rec off by 1e-6 relative', 'brief');
M = add(M, 'tau_rel_1e-6', pairs, ...
    'pair.tau_b_rel{pre, post} = tau_rel;', ...
    'pair.tau_b_rel{pre, post} = tau_rel .* (1 + 1e-6);', ...
    'every depression tau_rel off by 1e-6 relative', 'brief');
M = add(M, 'tau_a_rung_1e-6', pairs, ...
    'params.c = obj.c;', ...
    ['params.c = obj.c; for q = 1:obj.n_cellTypes, if ~isempty(params.tau_a_matrix{q}), ' ...
     'params.tau_a_matrix{q}(:, 1) = params.tau_a_matrix{q}(:, 1) .* (1 + 1e-6); end, end'], ...
    ['the first SFA rung of every neuron off by 1e-6 relative, in the tau_a_matrix the physics reads ' ...
     '(after the loop that fills it, so both the spread and the no-spread branch are covered)'], 'brief');
M = add(M, 'c_eff_no_K', pairs, ...
    'params.c_eff = obj.c ./ max(1, obj.n_a);', ...
    'params.c_eff = obj.c;', ...
    'c_eff: the division by the number of SFA timescales removed', 'brief');
M = add(M, 'G_1e-6', pairs, ...
    'pair.G{pre, post} = G;', ...
    'pair.G{pre, post} = G .* (1 + 1e-6);', ...
    'every facilitation ceiling G off by 1e-6 relative', 'brief');
M = add(M, 'tau_fac_1e-6', pairs, ...
    'pair.tau_g_fac{pre, post} = tau_fac;', ...
    'pair.tau_g_fac{pre, post} = tau_fac .* (1 + 1e-6);', ...
    'every facilitation tau_fac off by 1e-6 relative', 'brief');
M = add(M, 'tau_dec_1e-6', pairs, ...
    'pair.tau_g_dec{pre, post} = tau_dec;', ...
    'pair.tau_g_dec{pre, post} = tau_dec .* (1 + 1e-6);', ...
    'every facilitation tau_dec off by 1e-6 relative (the brief names G and tau_fac; this is the third facilitation parameter)', 'added');
M = add(M, 'tau_d_1e-6', pairs, ...
    'params.tau_d = obj.tau_d;', ...
    'params.tau_d = obj.tau_d .* (1 + 1e-6);', ...
    ['tau_d off by 1e-6 relative in params only. The parameter view stores the OBJECT''s tau_d, so this is ' ...
     'a parameter error the view cannot see: only dS, J and JY can'], 'added');
M = add(M, 'route_scale_not_folded', pairs, ...
    'if any(pair.scale(:) ~= 1)', ...
    'if false', ...
    'the route scale not folded into params.W', 'brief');
M = add(M, 'tau_rec_I_to_E_param_1e-6', pairs, ...
    'pair.tau_b_rec{pre, post} = tau_rec;', ...
    'pair.tau_b_rec{pre, post} = tau_rec .* (1 + 1e-6 * (pre == 2 && post == 1));', ...
    ['the I->E route''s tau_rec alone off by 1e-6, as a PARAMETER: the case known to make the reservoir ' ...
     'refuse the synaptic readout, kept to record what a thrown case looks like beside value failures'], 'added');

%% dynamics_fast
M = add(M, 'recovery_sign', pairs, ...
    '(1 - b_state{pre, post}) ./ params.tau_b_rec{pre, post} ...', ...
    '-(1 - b_state{pre, post}) ./ params.tau_b_rec{pre, post} ...', ...
    'dynamics_fast: the sign of the depression recovery term flipped', 'brief');
M = add(M, 'recovery_I_to_E_1e-6', pairs, ...
    '(1 - b_state{pre, post}) ./ params.tau_b_rec{pre, post} ...', ...
    '(1 + 1e-6 * (pre == 2 && post == 1)) .* (1 - b_state{pre, post}) ./ params.tau_b_rec{pre, post} ...', ...
    ['dynamics_fast: the recovery term of the I->E route alone scaled by 1 + 1e-6 (one route, in the arithmetic, ' ...
     'so no parameter differs between routes and nothing throws)'], 'brief');
M = add(M, 'release_1e-6', pairs, ...
    '- (b_state{pre, post} .* pre_rate) ...', ...
    '- (1 + 1e-6) .* (b_state{pre, post} .* pre_rate) ...', ...
    'dynamics_fast: the depression release term scaled by 1 + 1e-6 (the brief covers recovery; this is the other half of db/dt)', 'added');
M = add(M, 'fac_buildup_sign', pairs, ...
    '+ ((params.G{pre, post} - g_state{pre, post}) .* pre_rate) ...', ...
    '- ((params.G{pre, post} - g_state{pre, post}) .* pre_rate) ...', ...
    'dynamics_fast: the sign of the facilitation build-up term flipped (the facilitation counterpart of recovery_sign)', 'added');
M = add(M, 'sfa_drive_1e-6', pairs, ...
    'a_derivatives{q} = ((rate(idx) - a{q}) ./ params.tau_a_matrix{q});', ...
    'a_derivatives{q} = (((1 + 1e-6) .* rate(idx) - a{q}) ./ params.tau_a_matrix{q});', ...
    'dynamics_fast: the rate driving SFA scaled by 1 + 1e-6 (no listed mutation touches da/dt in the arithmetic)', 'added');
M = add(M, 'input_1e-6', pairs, ...
    '{(-x + recurrent + u) ./ params.tau_d}', ...
    '{(-x + recurrent + (1 + 1e-6) .* u) ./ params.tau_d}', ...
    'dynamics_fast: the external input scaled by 1 + 1e-6 (the term of dx/dt no route or Jacobian mutation reaches)', 'added');
M = add(M, 'geomean_plain_product_dS', pairs, ...
    ['depression = SRNNCellTypePairs.combine_std_pair( ...' nl sp(28) ...
     'prod(b_state{pre, post}, 2), params, pre, post);'], ...
    'depression = prod(b_state{pre, post}, 2);', ...
    'dynamics_fast only: the depression factor left as the plain product on a geomean route', 'brief');
M = add(M, 'zero_floor_off_dS', pairs, ...
    ['depression = SRNNCellTypePairs.apply_std_zero_floor_pair( ...' nl sp(24) ...
     'depression, params, pre, post);' nl sp(20) 'post_idx = params.type_indices{post};'], ...
    'post_idx = params.type_indices{post};', ...
    'dynamics_fast only: the zero floor not applied (the brief lists this for unpack_and_compute_states; the same omission in the right-hand side)', 'added');

%% The combine and the zero floor
M = add(M, 'p_min_1e-6', pairs, ...
    'p_min = SRNNCellTypePairs.combine_std_pair(p_min, params, pre, post);', ...
    'p_min = SRNNCellTypePairs.combine_std_pair(p_min, params, pre, post) .* (1 + 1e-6);', ...
    'the zero floor''s p_min off by 1e-6 relative', 'brief');
M = add(M, 'geomean_gain_omitted_J', pairs, ...
    ['gain = gain .* combine_gain;' nl sp(24) 'coeff = gain .* facilitation{pre, post} .* ...'], ...
    'coeff = gain .* facilitation{pre, post} .* ...', ...
    'compute_Jacobian_fast only: the geomean gain dD/dP omitted from the (x, b) block', 'brief');
M = add(M, 'geomean_gain_omitted_jt', pairs, ...
    ['gain = gain .* combine_gain;' nl sp(24) 'dtheta_b = gain .* reshape('], ...
    'dtheta_b = gain .* reshape(', ...
    'jacobian_times only: the geomean gain dD/dP omitted (the mirror of geomean_gain_omitted_J)', 'added');

%% The activation
M = add(M, 'phi_prime_1e-6', pairs, ...
    'dy = 4 .* value .* (1 - value);', ...
    'dy = 4 .* (1 + 1e-6) .* value .* (1 - value);', ...
    ['the logistic derivative off by 1e-6: every Jacobian block wrong in the same way in J and in jacobian_times, ' ...
     'with the right-hand side untouched, so only the stored Jacobians can see it'], 'added');

%% compute_Jacobian_fast: one block dropped per mutation
M = add(M, 'j_drop_a_x', pairs, ...
    'J(row_a, row_x) = sparse((1:numel(row_a))'', ...', ...
    'J(row_a, row_x) = 0 .* sparse((1:numel(row_a))'', ...', ...
    'compute_Jacobian_fast: the (a, x) block dropped', 'brief');
M = add(M, 'j_drop_a_a_coupling', pairs, ...
    'J(row_a, row_a) = diag_block + coupling;', ...
    'J(row_a, row_a) = diag_block;', ...
    'compute_Jacobian_fast: the coupling part of the (a, a) block dropped', 'brief');
M = add(M, 'j_drop_a_a_diagonal', pairs, ...
    'J(row_a, row_a) = diag_block + coupling;', ...
    'J(row_a, row_a) = coupling;', ...
    'compute_Jacobian_fast: the diagonal part of the (a, a) block dropped (the brief lists the coupling part only)', 'added');
M = add(M, 'j_drop_b_a', pairs, ...
    'J(row_b, row_a) = kron(sparse(ones(1, na)), stack);', ...
    'J(row_b, row_a) = 0 .* kron(sparse(ones(1, na)), stack);', ...
    'compute_Jacobian_fast: the (b, a) block dropped', 'brief');
M = add(M, 'j_drop_b_b', pairs, ...
    'J(row_b, row_b) = spdiags( ...', ...
    'J(row_b, row_b) = 0 .* spdiags( ...', ...
    'compute_Jacobian_fast: the (b, b) block dropped', 'brief');
M = add(M, 'j_drop_b_x', pairs, ...
    'J(row_b, row_x) = sparse(1:numel(row_b), ...', ...
    'J(row_b, row_x) = 0 .* sparse(1:numel(row_b), ...', ...
    'compute_Jacobian_fast: the (b, x) block dropped', 'brief');
M = add(M, 'j_drop_g_a', pairs, ...
    'J(row_g, row_a) = kron(sparse(ones(1, na)), stack);', ...
    'J(row_g, row_a) = 0 .* kron(sparse(ones(1, na)), stack);', ...
    'compute_Jacobian_fast: the (g, a) block dropped', 'brief');
M = add(M, 'j_drop_g_g', pairs, ...
    'J(row_g, row_g) = spdiags( ...', ...
    'J(row_g, row_g) = 0 .* spdiags( ...', ...
    'compute_Jacobian_fast: the (g, g) block dropped', 'brief');
M = add(M, 'j_drop_g_x', pairs, ...
    'J(row_g, row_x) = sparse(1:numel(row_g), ...', ...
    'J(row_g, row_x) = 0 .* sparse(1:numel(row_g), ...', ...
    'compute_Jacobian_fast: the (g, x) block dropped', 'brief');
M = add(M, 'j_drop_x_a', pairs, ...
    'block = -params.c_eff(pre) .* rate_block;', ...
    'block = 0 .* rate_block;', ...
    'compute_Jacobian_fast: the (x, a) block dropped', 'brief');
M = add(M, 'j_drop_x_b', pairs, ...
    'J(row_x(post_idx), row_b) = ...', ...
    'J(row_x(post_idx), row_b) = 0 .* ...', ...
    'compute_Jacobian_fast: the (x, b) block dropped', 'brief');
M = add(M, 'j_drop_x_g', pairs, ...
    'J(row_x(post_idx), row_g) = ...', ...
    'J(row_x(post_idx), row_g) = 0 .* ...', ...
    'compute_Jacobian_fast: the (x, g) block dropped', 'brief');
M = add(M, 'j_drop_x_x_rate_block', pairs, ...
    'J(row_x(post_idx), row_x(pre_idx)) + rate_block ./ params.tau_d;', ...
    'J(row_x(post_idx), row_x(pre_idx)) + 0 .* rate_block ./ params.tau_d;', ...
    'compute_Jacobian_fast: the rate_block of (x, x) dropped (the recurrent part; the leak stays)', 'brief');
M = add(M, 'j_drop_x_x_leak', pairs, ...
    'J(row_x, row_x) = spdiags(-ones(n, 1) ./ params.tau_d, 0, n, n);', ...
    'J(row_x, row_x) = sparse(n, n);', ...
    'compute_Jacobian_fast: the leak -1/tau_d of (x, x) dropped (the brief lists the rate_block only)', 'added');

%% jacobian_times: the matching term scaled by 1 + 1e-9
M = add(M, 'jt_a_x', pairs, ...
    'dr = rate_prime(idx) .* Ye{q};', ...
    'dr = rate_prime(idx) .* (Ye{q} + 1e-9 .* Yx(idx, :));', ...
    'jacobian_times: the (a, x) term scaled by 1 + 1e-9', 'brief');
M = add(M, 'jt_a_a_coupling', pairs, ...
    'dr = rate_prime(idx) .* Ye{q};', ...
    'dr = rate_prime(idx) .* (Ye{q} - 1e-9 .* params.c_eff(q) .* reshape(sum(Ya{q}, 2), nq, K));', ...
    'jacobian_times: the (a, a) coupling term scaled by 1 + 1e-9', 'brief');
M = add(M, 'jt_a_a_diagonal', pairs, ...
    'Za = -Ya{q} + reshape(dr, nq, 1, K);', ...
    'Za = -(1 + 1e-9) .* Ya{q} + reshape(dr, nq, 1, K);', ...
    'jacobian_times: the (a, a) diagonal term scaled by 1 + 1e-9 (mirror of j_drop_a_a_diagonal)', 'added');
M = add(M, 'jt_b_a', pairs, ...
    'Zb = diag_b .* Yb + coeff_b .* Ye_pre3;', ...
    'Zb = diag_b .* Yb + coeff_b .* (Ye_pre3 - 1e-9 .* params.c_eff(pre) .* sum(Ya{pre}, 2));', ...
    'jacobian_times: the (b, a) term scaled by 1 + 1e-9', 'brief');
M = add(M, 'jt_b_b', pairs, ...
    'Zb = diag_b .* Yb + coeff_b .* Ye_pre3;', ...
    'Zb = (1 + 1e-9) .* diag_b .* Yb + coeff_b .* Ye_pre3;', ...
    'jacobian_times: the (b, b) term scaled by 1 + 1e-9', 'brief');
M = add(M, 'jt_b_x', pairs, ...
    'Zb = diag_b .* Yb + coeff_b .* Ye_pre3;', ...
    'Zb = diag_b .* Yb + coeff_b .* (Ye_pre3 + 1e-9 .* reshape(Yx(pre_idx, :), npre, 1, K));', ...
    'jacobian_times: the (b, x) term scaled by 1 + 1e-9', 'brief');
M = add(M, 'jt_g_a', pairs, ...
    'Zg = diag_g .* Yg + coeff_g .* Ye_pre3;', ...
    'Zg = diag_g .* Yg + coeff_g .* (Ye_pre3 - 1e-9 .* params.c_eff(pre) .* sum(Ya{pre}, 2));', ...
    'jacobian_times: the (g, a) term scaled by 1 + 1e-9', 'brief');
M = add(M, 'jt_g_g', pairs, ...
    'Zg = diag_g .* Yg + coeff_g .* Ye_pre3;', ...
    'Zg = (1 + 1e-9) .* diag_g .* Yg + coeff_g .* Ye_pre3;', ...
    'jacobian_times: the (g, g) term scaled by 1 + 1e-9', 'brief');
M = add(M, 'jt_g_x', pairs, ...
    'Zg = diag_g .* Yg + coeff_g .* Ye_pre3;', ...
    'Zg = diag_g .* Yg + coeff_g .* (Ye_pre3 + 1e-9 .* reshape(Yx(pre_idx, :), npre, 1, K));', ...
    'jacobian_times: the (g, x) term scaled by 1 + 1e-9', 'brief');
M = add(M, 'jt_x_a', pairs, ...
    'dtheta = (facilitation .* depression_syn) .* dr_pre ...', ...
    ['dtheta = (facilitation .* depression_syn) .* (dr_pre - 1e-9 .* pre_rate_prime .* params.c_eff(pre) ' ...
     '.* reshape(sum(Ya{pre}, 2), npre, K)) ...'], ...
    'jacobian_times: the (x, a) term scaled by 1 + 1e-9', 'brief');
M = add(M, 'jt_x_b', pairs, ...
    '+ (facilitation .* pre_rate) .* dtheta_b ...', ...
    '+ (1 + 1e-9) .* (facilitation .* pre_rate) .* dtheta_b ...', ...
    'jacobian_times: the (x, b) term scaled by 1 + 1e-9', 'brief');
M = add(M, 'jt_x_g', pairs, ...
    '+ (depression_syn .* pre_rate) .* dtheta_g;', ...
    '+ (1 + 1e-9) .* (depression_syn .* pre_rate) .* dtheta_g;', ...
    'jacobian_times: the (x, g) term scaled by 1 + 1e-9', 'brief');
M = add(M, 'jt_x_x_rate_block', pairs, ...
    'dtheta = (facilitation .* depression_syn) .* dr_pre ...', ...
    'dtheta = (facilitation .* depression_syn) .* (dr_pre + 1e-9 .* pre_rate_prime .* Yx(pre_idx, :)) ...', ...
    'jacobian_times: the recurrent (x, x) term scaled by 1 + 1e-9', 'brief');
M = add(M, 'jt_x_x_leak', pairs, ...
    'Z(layout.x, :) = -Yx ./ params.tau_d;', ...
    'Z(layout.x, :) = -(1 + 1e-9) .* Yx ./ params.tau_d;', ...
    'jacobian_times: the leak term of (x, x) scaled by 1 + 1e-9 (mirror of j_drop_x_x_leak)', 'added');

%% initialize_state and unpack_and_compute_states
M = add(M, 'init_b_1e-6', pairs, ...
    'params.n_b_pairs(pre, post), 1);', ...
    'params.n_b_pairs(pre, post), 1) .* (1 - 1e-6);', ...
    'initialize_state: depression starting at 1 - 1e-6 instead of 1', 'brief');
M = add(M, 'unpack_no_facilitation', pairs, ...
    'facilitation .* depression .* rate(pre_idx, :);', ...
    'depression .* rate(pre_idx, :);', ...
    'unpack_and_compute_states: the facilitation factor dropped from the synaptic output', 'brief');
M = add(M, 'unpack_no_zero_floor', pairs, ...
    ['depression = SRNNCellTypePairs.apply_std_zero_floor_pair( ...' nl sp(24) ...
     'depression, params, pre, post);' nl sp(20) 'synaptic_output_named.(pre_name).(post_name) = ...'], ...
    'synaptic_output_named.(pre_name).(post_name) = ...', ...
    'unpack_and_compute_states: the zero floor not applied', 'brief');

%% The reservoir class, which the tier reaches only through memory capacity
M = add(M, 'esn_readout_rate_for_synaptic', esn, ...
    'first_route.(name) = syn_all.(name).(posts{1});', ...
    'first_route.(name) = r_all.(name);', ...
    ['SRNN_ESN_reservoir: the synaptic readout returns the rate (depression left out of the readout). FD-006 ' ...
     'rewrites this readout, and only the memory-capacity leaves, under their 1e-6 override, can see it'], 'added');
M = add(M, 'esn_ridge_eta_1e-3', esn, ...
    'w = (XTX + eta * eye(n_features)) \ XTy;', ...
    'w = (XTX + eta * (1 + 1e-3) * eye(n_features)) \ XTy;', ...
    ['SRNN_ESN_reservoir: the ridge regulariser off by 1e-3 relative. A PROBE of how fine an error in the ' ...
     'reservoir''s own arithmetic the 1e-6 override on MC and R2 still sees, not an error of the listed kind'], 'added');
end

function M = add(M, name, file, find_text, replace_text, what, origin)
M(end + 1) = struct('name', name, 'file', file, 'find', find_text, 'replace', replace_text, ...
    'what', what, 'origin', origin);
end
