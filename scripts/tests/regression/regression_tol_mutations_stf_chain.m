function M = regression_tol_mutations_stf_chain(which_list)
% REGRESSION_TOL_MUTATIONS_STF_CHAIN The deliberate errors in release-coupled facilitation that the tolerance tier's stf_chain suite must catch.
%
%   M = regression_tol_mutations_stf_chain()            % the list
%   G = regression_tol_mutations_stf_chain('groups')    % leaf groups for the harness
%   rows = regression_tol_mutate(M, 'reference', 'stf_chain', 'groups', G);
%
% DATA FOR regression_tol_mutate (Plan A, section 7.3, step 8; FD-018). The
% stf_chain suite of the tolerance tier (regression_tol_run, suite
% 'stf_chain'; reference scripts/tests/fixtures/regression_tol_stf_chain.mat)
% is the gate for work on route_pool's facilitation, the per-neuron spread
% first. Before it is trusted it has to be shown to catch errors in it.
% Each entry is one minimal one-site edit: a file, a text that occurs
% exactly once in it, and its replacement. THE TEXT IS TIED TO THE CODE AS
% IT STANDS at the commit that added this file.
%
% The route's equations, with d = h on a route with a calcium trace and
% d = r on one without (route_pool's header):
%   db1/dt = b2 (1 - b1)/tau_rec1 - g b1 r/tau_rel       no reserve: (1 - b1)/tau_rec1
%   dg/dt  = (1 - g)/tau_dec + (G - g) d/tau_fac
%   dh/dt  = (r - h)/tau_h
%   F      = g b1                                        no depression: g
%
% THE ERRORS, by where they are:
%   route_pool, linearize   every entry facilitation adds or changes,
%        dropped, with its sign flipped and scaled by 1 + 1e-9: (b1, g);
%        (g, g) with and without the trace; (g, h); (h, h); the rate
%        columns of g and of h; the factor g in (b1, b1) and in the rate
%        column of b1; F and Fs. Entries written in the wrong place:
%        (b1, g) and (g, h) transposed, the rate column of h written in
%        g's row. d = r where d = h belongs and the reverse, in A and in
%        B. Fs as if h were a factor of the output. The single pool's
%        (b1, b1) and the route without depression (F = g).
%   route_pool, rhs         each term of the g and h equations dropped and
%        scaled by 1 + 1e-6, with and without the trace; d = r used where
%        d = h belongs; the factor g in the release term and in F, each
%        dropped separately and each scaled; the single pool's refill.
%   route_pool, compile     tau_dec, tau_fac, G, tau_h off by 1e-6 in the
%        per-neuron values (the nominal rows, and so the parameter view,
%        right); one neuron's G; G and tau_h off in the nominal row; the
%        coupling understated in (b1, g) and in (g, h)
%   route_pool, initial (g, h), output, facilitation (g h for g)
%   route_model             the registry handing every pool route the
%        product model (a coupled route then runs with output-only
%        facilitation and no calcium trace)
%   SRNNCellTypePairs       params.stf_tau_h and params.stf_chain;
%        stf_route_factor returning the product of the g-block; a coupled
%        route's g and h rows exchanged; the g columns reversed in the
%        unpacking
% The errors in the chain's own lines (the 2 x 2 of b1 and b2, the reserve,
% the full-A branch of jacobian_times, a transposed block in the assembled
% Jacobian) are regression_tol_mutations_chain, run against the chain
% reference; the class-level errors that are not specific to a pool route
% are regression_tol_mutations_post_refactor, run against the anchor.
%
% NOT IN THE LIST, because it cannot be written as a one-site edit that
% runs: d = h used where d = r belongs IN THE RIGHT-HAND SIDE of a route
% without a calcium trace. Such a route has no h to read; the error would
% index a column that does not exist and throw. Its linearisation's form
% (the rate column of g zero, as on a route with a trace) is in the list.
%
% NAMING. A<m><k> is entry (m, k) of A = d(ds_m)/d(s_k), with the
% variables named b1, g, h; B<m> is d(ds_m)/dr.
%
% See also: regression_tol_mutate, regression_tol_mutations_chain,
%           regression_tol_check, route_pool
arguments
    which_list (1,:) char {mustBeMember(which_list, {'list', 'groups'})} = 'list'
end
if strcmp(which_list, 'groups')
    % What kind of leaf saw the error (first match wins; the overridden
    % groups of regression_tol_settings first), for the suite's keys.
    M = { ...
        'ov_orth_defect',   '(^|\.)orth_defect_max$'; ...
        'ov_fd_jacobian',   '(^|\.)finite_difference_J$'; ...
        'ov_qr',            '^stable\.estimators\.\w+\.qr\.'; ...
        'ov_mc',            '^stable\.mc\.\w+\.(MC|R2)$'; ...
        'pw_view',          '^pointwise\..*\.view\.'; ...
        'pw_dS',            '^pointwise\..*\.dS$'; ...
        'pw_J',             '^pointwise\..*\.J(\{\d+\}|#size)$'; ...
        'pw_JY',            '^pointwise\..*\.JY$'; ...
        'pw_rate_theta',    '^pointwise\..*\.(rate|synaptic_output)\.'; ...
        'pw_std_factor',    '^pointwise\..*\.std_factor\.'; ...
        'pw_stf_factor',    '^pointwise\..*\.stf_factor\.'; ...
        'pw_other',         '^pointwise\.'; ...
        'st_trajectory',    '^stable\.model\.\w+\.\w+\.(S0|S_kept|t_kept|W|plot_data\.|tau_a_clipped)'; ...
        'st_std_factor',    '^stable\.model\.\w+\.\w+\.std_factor\.'; ...
        'st_stf_factor',    '^stable\.model\.\w+\.\w+\.stf_factor\.'; ...
        'st_topk',          '^stable\.model\.\w+\.\w+\.(lya_results|lya_summary)\.'; ...
        'st_gain',          '^stable\.extra\.\w+\.transient_gain\.'; ...
        'st_benettin',      '^stable\.estimators\.\w+\.benettin\.'; ...
        'st_sweep',         '^stable\.sweep\.'; ...
        'st_other',         '^stable\.'};
    return;
end
pairs = 'src/model/SRNNCellTypePairs.m';
pool = 'src/model/routes/route_pool.m';
registry = 'src/model/routes/route_model.m';
M = struct('name', {}, 'file', {}, 'find', {}, 'replace', {}, 'what', {});
kinds = {'dropped', '0 .* (%s)', 'dropped'; ...
         'sign',    '-(%s)',     'with its sign flipped'; ...
         '1e-9',    '(1 + 1e-9) .* (%s)', 'scaled by 1 + 1e-9'};

%% route_pool, linearize: the entries of A and B that facilitation adds
% {name, left-hand side, right-hand side, what}. Each is one assignment.
entries = { ...
    'A_b1_g',   'A(:, (cg - 1) * ns + 1) = ', '-b1 .* r ./ P.tau_rel', ...
        '(b1, g): d(db1/dt)/dg = -b1 r/tau_rel, the entry that is new in kind'; ...
    'A_g_g_trace', 'A(:, at_gg) = ', '-1 ./ P.tau_dec - h ./ P.tau_fac', ...
        '(g, g) on a route with a calcium trace: -1/tau_dec - h/tau_fac'; ...
    'A_g_g_rate', 'A(:, at_gg) = ', '-1 ./ P.tau_dec - r ./ P.tau_fac', ...
        '(g, g) on a route without a calcium trace: -1/tau_dec - r/tau_fac'; ...
    'A_g_h',    'A(:, (ch - 1) * ns + cg) = ', '(P.G - g) ./ P.tau_fac', ...
        '(g, h): d(dg/dt)/dh = (G - g)/tau_fac'; ...
    'A_h_h',    'A(:, (ch - 1) * ns + ch) = ', '-1 ./ P.tau_h', ...
        '(h, h): -1/tau_h'; ...
    'B_h',      'B(:, ch) = ', '1 ./ P.tau_h', ...
        'the rate column of h: d(dh/dt)/dr = 1/tau_h'; ...
    'B_g',      'B(:, cg) = ', '(P.G - g) ./ P.tau_fac', ...
        'the rate column of g on a route without a trace: (G - g)/tau_fac'; ...
    'B_b1',     'B(:, 1) = ', '-g .* b1 ./ P.tau_rel', ...
        'the rate column of b1 with facilitation: -g b1/tau_rel'};
for e = 1:size(entries, 1)
    for k = 1:size(kinds, 1)
        M = add(M, sprintf('stf_%s_%s', entries{e, 1}, kinds{k, 1}), pool, ...
            [entries{e, 2} entries{e, 3} ';'], [entries{e, 2} sprintf(kinds{k, 2}, entries{e, 3}) ';'], ...
            sprintf('linearize: %s, %s', entries{e, 4}, kinds{k, 3}));
    end
end
% Entries in the wrong place.
M = add(M, 'stf_A_b1_g_transposed', pool, 'A(:, (cg - 1) * ns + 1) = -b1 .* r ./ P.tau_rel;', ...
    'A(:, cg) = -b1 .* r ./ P.tau_rel;', ...
    'linearize: (b1, g) written at (g, b1), as if depression drove facilitation');
M = add(M, 'stf_A_g_h_transposed', pool, 'A(:, (ch - 1) * ns + cg) = (P.G - g) ./ P.tau_fac;', ...
    'A(:, (cg - 1) * ns + ch) = (P.G - g) ./ P.tau_fac;', ...
    'linearize: (g, h) written at (h, g), as if g drove the calcium trace');
M = add(M, 'stf_B_h_on_g', pool, 'B(:, ch) = 1 ./ P.tau_h;', 'B(:, cg) = 1 ./ P.tau_h;', ...
    'linearize: the rate column of h written in g''s row');
% d = r where d = h belongs, and the reverse.
M = add(M, 'stf_A_g_g_d_r_for_h', pool, 'A(:, at_gg) = -1 ./ P.tau_dec - h ./ P.tau_fac;', ...
    'A(:, at_gg) = -1 ./ P.tau_dec - r ./ P.tau_fac;', ...
    'linearize, route with a trace: (g, g) evaluated with the rate where the calcium trace belongs');
M = add(M, 'stf_lin_d_r_for_h', pool, 'B(:, ch) = 1 ./ P.tau_h;', ...
    'B(:, ch) = 1 ./ P.tau_h; B(:, cg) = (P.G - g) ./ P.tau_fac;', ...
    ['linearize, route with a trace: the rate column of g filled as if the rate drove g directly ' ...
     '(it must be zero: the rate reaches g only through h)']);
M = add(M, 'stf_lin_d_h_for_r', pool, 'B(:, cg) = (P.G - g) ./ P.tau_fac;', ...
    'B(:, cg) = 0 .* g;', ...
    ['linearize, route without a trace: the rate column of g left zero, as on a route with a trace ' ...
     '(d = h where d = r belongs)']);
% The factor g where facilitation changes a depression entry.
use_line = 'use = g .* r ./ P.tau_rel;';
M = add(M, 'stf_A_b1_b1_g_dropped', pool, use_line, 'use = r ./ P.tau_rel;', ...
    'linearize: (b1, b1) without the factor g in its release part (-b2/tau_rec1 - r/tau_rel)');
M = add(M, 'stf_A_b1_b1_g_1e-9', pool, use_line, 'use = (1 + 1e-9) .* g .* r ./ P.tau_rel;', ...
    'linearize: the release part of (b1, b1), g r/tau_rel, scaled by 1 + 1e-9');
M = add(M, 'stf_B_b1_g_dropped', pool, 'B(:, 1) = -g .* b1 ./ P.tau_rel;', 'B(:, 1) = -b1 ./ P.tau_rel;', ...
    'linearize: the rate column of b1 without the factor g');
single_A = 'A(:, 1) = -1 ./ P.tau_rec1 - use;';
M = add(M, 'stf_single_A_b1_b1_dropped', pool, single_A, 'A(:, 1) = 0 .* (-1 ./ P.tau_rec1 - use);', ...
    'linearize, single pool: (b1, b1) = -1/tau_rec1 - g r/tau_rel dropped');
M = add(M, 'stf_single_A_b1_b1_1e-9', pool, single_A, 'A(:, 1) = (1 + 1e-9) .* (-1 ./ P.tau_rec1 - use);', ...
    'linearize, single pool: (b1, b1) scaled by 1 + 1e-9');
M = add(M, 'stf_single_A_b1_b1_as_chain', pool, single_A, 'A(:, 1) = -use;', ...
    'linearize, single pool: (b1, b1) without its refill part -1/tau_rec1');

%% route_pool, linearize: F and Fs
F_line = ['    F = g .* b1;' newline '    Fs(:, 1) = g;'];
M = add(M, 'stf_lin_F_g_dropped', pool, F_line, ['    F = b1;' newline '    Fs(:, 1) = g;'], ...
    'linearize: the output factor returned as b1, without g (the recurrent (x, x) and (x, a) blocks)');
M = add(M, 'stf_lin_F_1e-9', pool, F_line, ['    F = (1 + 1e-9) .* g .* b1;' newline '    Fs(:, 1) = g;'], ...
    'linearize: the output factor g b1 scaled by 1 + 1e-9');
M = add(M, 'stf_Fs_b1_dropped', pool, 'Fs(:, 1) = g;', 'Fs(:, 1) = 0 .* g;', ...
    'linearize: dF/db1 = g dropped');
M = add(M, 'stf_Fs_b1_g_dropped', pool, 'Fs(:, 1) = g;', 'Fs(:, 1) = 1;', ...
    'linearize: dF/db1 = 1, as on a route without facilitation');
M = add(M, 'stf_Fs_b1_1e-9', pool, 'Fs(:, 1) = g;', 'Fs(:, 1) = (1 + 1e-9) .* g;', ...
    'linearize: dF/db1 scaled by 1 + 1e-9');
M = add(M, 'stf_Fs_g_dropped', pool, 'Fs(:, cg) = b1;', 'Fs(:, cg) = 0 .* b1;', ...
    'linearize: dF/dg = b1 dropped');
M = add(M, 'stf_Fs_g_1e-9', pool, 'Fs(:, cg) = b1;', 'Fs(:, cg) = (1 + 1e-9) .* b1;', ...
    'linearize: dF/dg scaled by 1 + 1e-9');
M = add(M, 'stf_Fs_h_as_factor', pool, 'Fs(:, cg) = b1;', ...
    'Fs(:, cg) = b1; if P.has_h, Fs(:, cg + 1) = g .* b1; end', ...
    'linearize: dF/dh filled as if the calcium trace multiplied the output');
nodep = ['        F = g;' newline '        Fs(:, cg) = 1;'];
M = add(M, 'stf_nodep_Fs_dropped', pool, nodep, ['        F = g;' newline '        Fs(:, cg) = 0;'], ...
    'linearize, route without depression: dF/dg = 1 dropped');
M = add(M, 'stf_nodep_Fs_1e-9', pool, nodep, ['        F = g;' newline '        Fs(:, cg) = 1 + 1e-9;'], ...
    'linearize, route without depression: dF/dg scaled by 1 + 1e-9');
M = add(M, 'stf_nodep_lin_F_1e-9', pool, nodep, ['        F = (1 + 1e-9) .* g;' newline '        Fs(:, cg) = 1;'], ...
    'linearize, route without depression: the output factor g scaled by 1 + 1e-9');

%% route_pool, rhs: the terms of the g and h equations
trace_line = 'dg = [(1 - g) ./ P.tau_dec + (P.G - g) .* h ./ P.tau_fac, (r - h) ./ P.tau_h];';
trace_fmt = 'dg = [%s + %s, (%s - %s) ./ P.tau_h];';
term = {'(1 - g) ./ P.tau_dec', '(P.G - g) .* h ./ P.tau_fac', 'r', 'h'};
term_name = {'g_decay', 'g_drive', 'h_rate', 'h_decay'};
term_what = {'dg/dt: the decay to rest (1 - g)/tau_dec', 'dg/dt: the drive (G - g) h/tau_fac', ...
    'dh/dt: the rate term r/tau_h', 'dh/dt: the decay -h/tau_h'};
for e = 1:4
    for k = 1:2
        parts = term;
        if k == 1
            parts{e} = ['0 .* ' term{e}];
            tag = 'dropped'; how = 'dropped';
        else
            parts{e} = ['(1 + 1e-6) .* ' term{e}];
            tag = '1e-6'; how = 'scaled by 1 + 1e-6';
        end
        M = add(M, sprintf('stf_rhs_trace_%s_%s', term_name{e}, tag), pool, trace_line, ...
            sprintf(trace_fmt, parts{:}), sprintf('rhs, route with a trace, %s, %s', term_what{e}, how));
    end
end
M = add(M, 'stf_rhs_d_r_for_h', pool, trace_line, ...
    'dg = [(1 - g) ./ P.tau_dec + (P.G - g) .* r ./ P.tau_fac, (r - h) ./ P.tau_h];', ...
    'rhs, route with a trace: g driven by the rate where the calcium trace belongs (d = r for d = h)');
rate_line = 'dg = (1 - g) ./ P.tau_dec + (P.G - g) .* r ./ P.tau_fac;';
rate_fmt = 'dg = %s + %s;';
term = {'(1 - g) ./ P.tau_dec', '(P.G - g) .* r ./ P.tau_fac'};
term_name = {'g_decay', 'g_drive'};
term_what = {'dg/dt: the decay to rest (1 - g)/tau_dec', 'dg/dt: the drive (G - g) r/tau_fac'};
for e = 1:2
    for k = 1:2
        parts = term;
        if k == 1
            parts{e} = ['0 .* ' term{e}];
            tag = 'dropped'; how = 'dropped';
        else
            parts{e} = ['(1 + 1e-6) .* ' term{e}];
            tag = '1e-6'; how = 'scaled by 1 + 1e-6';
        end
        M = add(M, sprintf('stf_rhs_rate_%s_%s', term_name{e}, tag), pool, rate_line, ...
            sprintf(rate_fmt, parts{:}), sprintf('rhs, route without a trace, %s, %s', term_what{e}, how));
    end
end

%% route_pool, rhs: the factor g in the release term and in F
release = 'release = g .* b1 .* r ./ P.tau_rel;';
M = add(M, 'stf_rhs_release_g_dropped', pool, release, 'release = b1 .* r ./ P.tau_rel;', ...
    'rhs: the release term without g (facilitation acting on the output only, as on a product route)');
M = add(M, 'stf_rhs_release_g_1e-6', pool, release, 'release = (1 + 1e-6) .* g .* b1 .* r ./ P.tau_rel;', ...
    'rhs: the release term g b1 r/tau_rel scaled by 1 + 1e-6');
rhs_F = ['    ds = [db, dg];' newline '    F = g .* b1;'];
M = add(M, 'stf_rhs_F_g_dropped', pool, rhs_F, ['    ds = [db, dg];' newline '    F = b1;'], ...
    'rhs: the output factor without g (facilitation acting on the pool''s use only)');
M = add(M, 'stf_rhs_F_1e-6', pool, rhs_F, ['    ds = [db, dg];' newline '    F = (1 + 1e-6) .* g .* b1;'], ...
    'rhs: the output factor g b1 scaled by 1 + 1e-6');
M = add(M, 'stf_rhs_F_g_h', pool, rhs_F, ...
    ['    ds = [db, dg];' newline '    F = g .* b1; if P.has_h, F = F .* h; end'], ...
    'rhs: the output factor g h b1 on a route with a trace, as if h were a facilitation component');
rhs_nodep = ['        ds = dg;' newline '        F = g;'];
M = add(M, 'stf_rhs_nodep_F_1e-6', pool, rhs_nodep, ['        ds = dg;' newline '        F = (1 + 1e-6) .* g;'], ...
    'rhs, route without depression: the output factor g scaled by 1 + 1e-6');
single = 'db = (1 - b1) ./ P.tau_rec1 - release;';
M = add(M, 'stf_rhs_single_refill_dropped', pool, single, 'db = 0 .* (1 - b1) ./ P.tau_rec1 - release;', ...
    'rhs, single pool: the refill (1 - b1)/tau_rec1 dropped');
M = add(M, 'stf_rhs_single_refill_1e-6', pool, single, 'db = (1 + 1e-6) .* (1 - b1) ./ P.tau_rec1 - release;', ...
    'rhs, single pool: the refill scaled by 1 + 1e-6');

%% route_pool, compile: the parameters the arithmetic reads, the coupling
names = {'tau_dec', 'tau_fac', 'G', 'tau_h'};
lines = {'P.tau_dec = repmat(nominal.tau_dec, npre, 1);', 'P.tau_fac = repmat(nominal.tau_fac, npre, 1);', ...
    'P.G       = repmat(nominal.G, npre, 1);', 'P.tau_h = repmat(nominal.tau_h, npre, 1);'};
for k = 1:4
    M = add(M, sprintf('stf_P_%s_1e-6', names{k}), pool, lines{k}, ...
        [lines{k}(1:end - 1) ' .* (1 + 1e-6);'], ...
        sprintf('the per-neuron %s off by 1e-6 with the nominal row right, so the parameter view cannot see it', names{k}));
end
M = add(M, 'stf_P_one_neuron_G_1e-6', pool, lines{3}, [lines{3} ' P.G(1) = P.G(1) .* (1 + 1e-6);'], ...
    'ONE neuron''s ceiling G off by 1e-6 (the first neuron of every presynaptic type with a coupled route)');
M = add(M, 'stf_nominal_G_1e-6', pool, 'nominal.G = double(stf_cfg.G);', ...
    'nominal.G = double(stf_cfg.G) .* (1 + 1e-6);', ...
    'G off by 1e-6 in the nominal row (and so in the per-neuron values, the signature and params.G)');
M = add(M, 'stf_nominal_tau_h_1e-6', pool, 'nominal.tau_h = double(tau_h);', ...
    'nominal.tau_h = double(tau_h) .* (1 + 1e-6);', ...
    'tau_h off by 1e-6 in the nominal row (and so in the per-neuron values, the signature and params.stf_tau_h)');
M = add(M, 'stf_params_tau_h_1e-6', pairs, 'pair.stf_tau_h(pre, post) = nominal.tau_h;', ...
    'pair.stf_tau_h(pre, post) = nominal.tau_h .* (1 + 1e-6);', ...
    'params.stf_tau_h, the copy display code reads, off by 1e-6 (no arithmetic reads it)');
M = add(M, 'stf_params_stf_chain_false', pairs, 'pair.stf_chain(pre, post) = true;', ...
    'pair.stf_chain(pre, post) = false;', ...
    'params.stf_chain false on every coupled route (no arithmetic reads it; display code labels by it)');
M = add(M, 'stf_coupling_b1_g_understated', pool, 'coupling(1, [1 2 3]) = true;', 'coupling(1, [1 2]) = true;', ...
    ['compile: the coupling without (b1, g). On a single pool with g the block is then stated diagonal, ' ...
     'and jacobian_times, which trusts the statement, applies only the diagonal of A']);
M = add(M, 'stf_coupling_g_h_understated', pool, 'coupling(3, [3 4]) = true;', 'coupling(3, 3) = true;', ...
    'compile: the coupling without (g, h). A route with g and h alone is then stated diagonal');

%% route_pool: initial, output, facilitation
s0_line = 'P.s0 = [ones(1, P.n_b + P.has_g), zeros(1, P.has_h)];';
M = add(M, 'stf_init_h_1e-6', pool, s0_line, [s0_line ' if P.has_h, P.s0(end) = 1e-6; end'], ...
    'initial: the calcium trace starting at 1e-6 and not at 0');
M = add(M, 'stf_init_h_one', pool, s0_line, 'P.s0 = ones(1, P.n_b + P.n_g);', ...
    'initial: the calcium trace starting at 1, as every other route variable does');
M = add(M, 'stf_init_g_1e-6', pool, s0_line, [s0_line ' if P.has_g, P.s0(P.n_b + 1) = 1 + 1e-6; end'], ...
    'initial: the release probability starting at 1 + 1e-6');
out_line = 'F = s(:, P.n_b + 1, :) .* s(:, 1, :);     % g b1';
M = add(M, 'stf_output_g_dropped', pool, out_line, 'F = s(:, 1, :);', ...
    'output: the factor returned as b1, without g (the unpacked synaptic output; rhs and linearize keep g b1)');
M = add(M, 'stf_output_g_h', pool, out_line, ...
    'F = s(:, P.n_b + 1, :) .* s(:, 1, :); if P.has_h, F = F .* s(:, P.n_b + 2, :); end', ...
    'output: the factor returned as g h b1 on a route with a trace');
M = add(M, 'stf_output_nodep_g_h', pool, 'F = s(:, 1, :);                           % g', ...
    'F = prod(s, 2);', ...
